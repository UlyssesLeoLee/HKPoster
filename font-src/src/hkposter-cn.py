"""HK Poster Heavy —— Wave 1 简体中文衍生字。

字符清单（CONTRACT §5 冻结，不得增删）：
    龙 U+9F99 / 义 U+4E49 / 爱 U+7231 / 无 U+65E0
    风 U+98CE / 电 U+7535 / 击 U+51FB / 间 U+95F4

设计取舍记录
------------
1. **只做简体专有字**：港 影 警 道 城 火 夜 这 七个字简繁同形，
   直接复用 Wave 0 的 master（hkposter-cjk-core / hkposter-cjk-dense），
   本 lane 不重做，避免同一字重复占用墨量统计。
2. **配重整体上调一档**（design-params.json → weights.cjk_simplified）：
   繁体 主/次/细 = 96/92/84，本 lane 取 **主 108 / 次 100 / 细 92 / 点 92**。
   理由：简体字的笔画数普遍比繁体少 40%–60%，若沿用繁体的绝对笔画宽度，
   简体在同一张海报里会被读成"轻一号"。上调一档后简繁同字号并排，
   视觉黑度接近（页脚留白与顶线高度均不变）。
3. **字面框与繁体完全一致**：advance 固定 1000，ink 控制在 x 60..940、y 0..825
   量级（繁体实测 x 60..970、y 0..847），简繁混排时基线与顶线齐平。
4. **笔画少的字（义 / 无 / 击）必须加粗并拉开内白**：这三字笔画总数只有
   3–5 笔，在标题尺寸下最容易看成细体，故主笔画一律 108，部件间距 ≥ 60 单位，
   保证缩到 24px 以下仍是黑块而不是发丝。
5. **用简体规范形，不做"繁体删几笔"**（逐字对照系统黑体核过）：
   龙 = 尤 + 丿（不是 龍）/ 义 = 丶 + 乂（不是 義）/ 爱 = 爫 + 冖 + 友（不是 愛）/
   无 = 一 + 一 + 儿（不是 無）/ 风 = 几 + 乂（不是 風）/ 电 = 日 + 乚（不是 電）/
   击 = 二 + 凵（不是 擊）/ 间 = 门 + 日（不是 間）。
   其中「电」的中央竖是「申」留下的骨架：日 的四格 + 中央竖下探成乚，
   与 電（雨 + 申）同源；「风」的内乂撇必须穿出外框左下（"不包裹"）。
6. **竖弯钩不做折线台阶**：第一版把「竖 + 弯斜 + 底横 + 钩」用四段拼，
   渲染出来是一串台阶，像"之"字；本版统一改为
   **竖 → 直角底横 → 钩**，用直角弯取代斜折弯，字形立刻干净。
7. **出锋笔画必须冲出去**（GLY-002 硬折）：龙的撇冲出左下、电的钩冲出到右、
   风的内乂撇穿出外框左下、门的钩向左回挑——终端都要看得见。
8. **坐标全部取整**；只使用 hkbuild 与标准库；recipe 为纯函数，生成物确定。
"""

from __future__ import annotations

import sys
from pathlib import Path

FONT_SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FONT_SRC / "scripts"))

from hkbuild import Glyph, write_ufo  # noqa: E402

# ---- 冻结权重（CONTRACT §2；design-params.json weights.cjk_simplified）----
W_MAIN = 108  # 主笔画
W_SEC = 100  # 次笔画
W_THIN = 92  # 细笔画（横杠 / 钩）
W_DOT = 92  # 点 / 短撇


# ---------------------------------------------------------------------------
# 龙 U+9F99 —— 「尤 + 丿」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_long() -> Glyph:
    """龙。

    自上而下：
      一 (636..744)                     顶横，x 170..810
      丿 (25..780)                      长撇，自 (300,780) 冲出左下至 (110,25)
      乚 = 竖(240..700) + 底(240) + 钩(240..360)
      丿 (290..460)                     中部短撇——龙与尤的唯一区别
      丶 (517..623)                     腔内右上方的点
    取舍：
      * 顶横与长撇上端错开，撇尖冲出到 x 110 / y 25，是全字的出气口；
      * 乚 的竖落在 x 650（字宽 65%），底横拉到 x 870 再回挑，
        与系统黑体的「龙」同一比例；
      * 短撇与点都收在 尤 的空腔里：短撇在腔左下、点在腔右上，
        两者与顶横、乚 的竖都留 25 单位以上白口，不会黏成块；
      * 乚 的弯用直角（竖直接落到底横），不用斜折，避免出现台阶。
    """
    g = Glyph("uni9F99", advance=1000, unicode=0x9F99, note="龙（Wave 1 简体中文）")

    g.hbar(170, 810, 690, weight=W_MAIN)  # 顶横（一）
    g.diag(300, 780, 110, 25, weight=W_SEC)  # 长撇（冲出左下）

    # 乚：竖 + 直角底 + 钩
    g.vbar(650, 240, 700, weight=W_SEC)  # 乚的竖
    g.hbar(650, 870, 240, weight=W_SEC)  # 乚的底
    g.diag(870, 240, 890, 360, weight=W_THIN)  # 乚的钩（出锋向上）

    g.diag(500, 460, 340, 290, weight=W_THIN)  # 中部短撇（龙 ≠ 尤）
    g.dot(530, 570, w=W_DOT, h=105, slant=22)  # 腔内的点
    return g


# ---------------------------------------------------------------------------
# 义 U+4E49 —— 「丶 + 乂」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_yi() -> Glyph:
    """义。

    自上而下：
      丶 (660..820)                     顶上的大点，x 430，向右下倾 22°
      乂 = 丿(40..655) + 捺(40..670)      两笔在 (464,444) 交叉
    取舍：
      * 义 只有 3 笔，是本 lane 最"空"的字，故两笔长撇捺一律取 108 主权重，
        且都拉到字面框的四角（x 90..910、y 40..670），把墨量补到与
        龙 / 无 同档；
      * 顶上的点用 130×160 的大水滴（其余字的点只到 92），
        因为它是本字唯一的"第三笔"，必须能撑住上部的视觉重量；
      * 交叉点定在 (464,444)（约 54% 字高），点落在交叉点正上方，
        这是 义 的规范关系；
      * 撇尖与捺脚都落在 y 40 附近，墨迹最低点 ≈ 0，基线与繁体齐平。
        已知取舍：本字墨量率必然低于家族中位数（3 笔字的上限），
        与繁体的 火 同属"轻字"档，见 check_glyphs 的 WARN 说明。
    """
    g = Glyph("uni4E49", advance=1000, unicode=0x4E49, note="义（Wave 1 简体中文）")

    g.dot(430, 740, w=130, h=160, slant=22)  # 顶上的大点
    g.diag(660, 655, 90, 40, weight=W_MAIN)  # 乂的撇
    g.diag(215, 670, 910, 40, weight=W_MAIN)  # 乂的捺
    return g


# ---------------------------------------------------------------------------
# 爱 U+7231 —— 「爫 + 冖 + 友」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_ai() -> Glyph:
    """爱。

    自上而下：
      爫 = 撇(704..822) + 三点(587..673)
      冖 = 横(451..559) + 左垂(360..455) + 右垂(360..455)
      友 = 一(320..420) + 撇(60..410) + 又 = 横(189..281) + 撇(45..235) + 捺(55..155)
    取舍：
      * 爱比 愛 少一层（无心部），所以 爫 的三层间距拉到 35–70 单位：
        爫 撇的墨迹下沿 704，点顶 587，冖 横的墨迹上沿 451，
        三层之间都能透出白，不会糊成一坨；
      * 爫 的三点用 84×86 的小水滴（比别处的点小），
        三个点之间留 180 单位，彼此不会连成横画；
      * 冖 的横是全字最长的横（80..870），把下部的 友 盖住，
        这是 爱 与 愛 在剪影上的最大区别；
      * 友 的长撇从 410 冲到 (95,60)，末端的 又 捺冲到 (850,55)，
        两端出气，左下与右下同时打开，墨迹最低点不低于 -2；
      * 友 的「一」只用 100，避免与 冖 的横黏成两条平行黑带。
    """
    g = Glyph("uni7231", advance=1000, unicode=0x7231, note="爱（Wave 1 简体中文）")

    # ---- 爫 ----
    g.diag(220, 750, 730, 776, weight=W_THIN)  # 爫的撇
    g.dot(300, 630, w=84, h=86, slant=-14)  # 爫的点 1
    g.dot(480, 630, w=84, h=86, slant=-14)  # 爫的点 2
    g.dot(660, 630, w=84, h=86, slant=-14)  # 爫的点 3

    # ---- 冖 ----
    g.hbar(80, 870, 505, weight=W_MAIN)  # 冖的横
    g.vbar(130, 360, 455, weight=W_THIN)  # 冖的左垂
    g.vbar(820, 360, 455, weight=W_THIN)  # 冖的右垂

    # ---- 友 ----
    g.hbar(190, 640, 370, weight=W_SEC)  # 友的一
    g.diag(430, 410, 95, 60, weight=W_SEC)  # 友的撇
    g.hbar(430, 700, 235, weight=W_THIN)  # 又的横
    g.diag(700, 235, 350, 45, weight=W_THIN)  # 又的撇
    g.diag(400, 155, 850, 55, weight=W_MAIN)  # 又的捺
    return g


# ---------------------------------------------------------------------------
# 无 U+65E0 —— 「一 + 一 + 儿」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_wu() -> Glyph:
    """无。

    自上而下：
      一 (646..754)                     上横，x 220..780
      一 (416..524)                     下横，x 60..880（更长）
      丿 (30..700)                      长撇，自上横左端斜穿下横到 (110,30)
      乚 = 竖(200..460) + 底(200) + 钩(200..300)
    取舍：
      * 无 与 元 的区别全在左边：撇从**上横的左端**起笔、斜穿下横，
        撇尖落在 (110,30)，把两横连成一个「斜穿的 Z」，
        这是简体规范形，不是"删几笔"；
      * 撇用 100 而非 108，因为它要穿过两横，粗了会把两横黏死；
      * 乚 的竖从上横的下沿 460 起笔，与下横的墨迹相接，
        右侧留白口 ≥ 250 单位，保证 儿 的两笔不并行成「门」；
      * 乚 的底横与竖成直角，钩向右上回挑，不做斜折台阶。
    """
    g = Glyph("uni65E0", advance=1000, unicode=0x65E0, note="无（Wave 1 简体中文）")

    g.hbar(220, 780, 700, weight=W_MAIN)  # 上横（一）
    g.hbar(60, 880, 470, weight=W_MAIN)  # 下横（一）
    g.diag(250, 700, 110, 30, weight=W_SEC)  # 长撇（自上横左端斜穿下横）

    # 乚：竖 + 直角底 + 钩
    g.vbar(620, 200, 460, weight=W_MAIN)  # 乚的竖
    g.hbar(620, 860, 200, weight=W_MAIN)  # 乚的底
    g.diag(860, 200, 880, 300, weight=W_THIN)  # 乚的钩
    return g


# ---------------------------------------------------------------------------
# 风 U+98CE —— 「几 + 乂」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_feng() -> Glyph:
    """风。

    自上而下：
      几 = 撇(50..790) + 横(716..824) + 竖(200..770) + 底(200) + 钩(200..320)
      乂 = 撇(190..640) + 捺(90..620)，在 (379,445) 交叉
    取舍：
      * 外框「几」**不包裹**内乂：内乂的撇从 (600,640) 一路斜下，
        在 y≈259 处穿出几的左撇，撇尖落在 (90,190)，
        在字面框左下角露出——这是 风 与 風 在剪影上的根本区别；
      * 几的横折弯钩把右下的钩冲到 x 890，与内乂的捺（止于 x 640）
        拉开，右下角也留出白口；
      * 几的底横落在 y 200，与内乂的捺脚（y 90）同带，
        整个下半部仍然通透，不会挤成一块黑；
      * 内乂用 108 主权重，几的框用 108，保证"框"与"内容"都有存在感。
    """
    g = Glyph("uni98CE", advance=1000, unicode=0x98CE, note="风（Wave 1 简体中文）")

    # ---- 几 ----
    g.diag(240, 790, 140, 50, weight=W_MAIN)  # 几的撇
    g.hbar(200, 680, 770, weight=W_MAIN)  # 几的横
    g.vbar(680, 200, 770, weight=W_MAIN)  # 几的竖（横折）
    g.hbar(680, 880, 200, weight=W_MAIN)  # 几的底
    g.diag(880, 200, 900, 320, weight=W_THIN)  # 几的钩

    # ---- 内乂（穿出外框左下）----
    g.diag(600, 640, 90, 190, weight=W_MAIN)  # 乂的撇
    g.diag(250, 620, 640, 90, weight=W_MAIN)  # 乂的捺
    return g


# ---------------------------------------------------------------------------
# 电 U+7535 —— 「日 + 乚」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_dian() -> Glyph:
    """电。

    自上而下：
      日 = 顶横(646..754) + 左竖(290..700) + 右竖(290..700)
           + 中横(444..536) + 底横(244..336)
      乚 = 竖(100..700，穿过日的中央) + 底(46..154) + 钩(100..220)
    取舍：
      * 电 是 電（雨 + 申）的简化，中央竖是 申 留下的骨架：
        日 的四格（上下各两格）因此才与 電 同源，竖从上横一路落到
        日 的下方，再向右弯出钩——所以中央竖用 100 而非 108，
        免得把四格内白挤没；
      * 日 的框只占 x 120..760（与系统黑体一致，右侧留给钩），
        四格内白：横间 108 单位、竖间 220 单位；
      * 竖弯钩的钩冲到 x 880（墨迹右缘 ≈ 926），是全字唯一的出锋，
        与 電 的"电"钩同向，保证混排时右下重心一致；
      * 钩用直角弯（竖直接落到底横），不做斜折台阶。
    """
    g = Glyph("uni7535", advance=1000, unicode=0x7535, note="电（Wave 1 简体中文）")

    # ---- 日 ----
    g.hbar(120, 760, 700, weight=W_MAIN)  # 日的顶横
    g.vbar(120, 290, 700, weight=W_SEC)  # 日的左竖
    g.vbar(760, 290, 700, weight=W_SEC)  # 日的右竖
    g.hbar(120, 760, 490, weight=W_THIN)  # 日的中横
    g.hbar(120, 760, 290, weight=W_THIN)  # 日的底横

    # ---- 乚（中央竖下探并向右冲出钩）----
    g.vbar(440, 100, 700, weight=W_SEC)  # 乚的竖（贯穿日的中线）
    g.hbar(440, 860, 100, weight=W_MAIN)  # 乚的底
    g.diag(860, 100, 880, 220, weight=W_THIN)  # 乚的钩
    return g


# ---------------------------------------------------------------------------
# 击 U+51FB —— 「二 + 凵」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_ji() -> Glyph:
    """击。

    自上而下：
      一 (666..774)                     上横，x 240..760
      一 (466..574)                     下横，x 80..920（更长）
      凵 = 左竖(60..380) + 底(20..120) + 右竖(60..380)
    取舍：
      * 击 只有 5 笔，两横全部取 108，是本 lane 最"横"的一个字；
      * 凵 的两竖只到 y 380，与下横的墨迹下沿 466 之间留 86 单位白口，
        这是 击 的字腔（与规范字形一致：凵 不封到第二横）；
      * 凵 的宽度 250..750 明显窄于下横 80..920，
        保证剪影上"上窄下宽"的层级不被拉平；
      * 底横落在 y 70（墨迹 20..120），墨迹最低点 ≈ 20，与繁体 擊 的
        底部重量分布一致。
    """
    g = Glyph("uni51FB", advance=1000, unicode=0x51FB, note="击（Wave 1 简体中文）")

    g.hbar(240, 760, 720, weight=W_MAIN)  # 上横（一）
    g.hbar(80, 920, 520, weight=W_MAIN)  # 下横（一）

    # 凵：左竖 + 底 + 右竖
    g.vbar(250, 70, 380, weight=W_SEC)  # 凵的左竖
    g.hbar(250, 750, 70, weight=W_SEC)  # 凵的底
    g.vbar(750, 70, 380, weight=W_SEC)  # 凵的右竖
    return g


# ---------------------------------------------------------------------------
# 间 U+95F4 —— 「门 + 日」（简体规范形）
# ---------------------------------------------------------------------------
def glyph_jian() -> Glyph:
    """间。

    自上而下：
      门 = 丶(735..835) + 左竖(40..690) + 顶横(686..794) + 折竖(60..740) + 钩(45..145)
      日 = 顶横(554..646) + 中横(354..446) + 底横(154..246)
           + 左竖(200..600) + 右竖(200..600)
    取舍：
      * 门**不封口**：左竖与折竖之间没有任何横相连，底部只在右边留一个
        向左回挑的钩（790,130），右下缺口是「门」与「日」的本质区别；
      * 顶横起笔在 x 200，与左竖（x 110，墨迹 60..160）之间留 40 单位空档，
        左上角由 丶 补上，这是 门 的规范结构；
      * 日 居于右下（两格），格内白 108 单位高、278 单位宽，
        与 门 的左竖之间留 124 单位，与折竖之间留 116 单位，
        三面都有白口，不会糊成一块；
      * 日 的右缘（746）与折竖的左缘（816）之间留 70 单位，
        门 内不会读成「闷」。
    """
    g = Glyph("uni95F4", advance=1000, unicode=0x95F4, note="间（Wave 1 简体中文）")

    # ---- 门 ----
    g.dot(130, 785, w=W_DOT, h=100, slant=22)  # 门的点
    g.vbar(110, 40, 690, weight=W_SEC)  # 门的左竖
    g.hbar(200, 870, 740, weight=W_MAIN)  # 门的顶横
    g.vbar(870, 60, 740, weight=W_MAIN)  # 门的折竖
    g.diag(870, 60, 790, 130, weight=W_THIN)  # 门的钩（向左回挑）

    # ---- 日 ----
    g.hbar(330, 700, 600, weight=W_THIN)  # 日的顶横
    g.vbar(330, 200, 600, weight=W_THIN)  # 日的左竖
    g.vbar(700, 200, 600, weight=W_THIN)  # 日的右竖
    g.hbar(330, 700, 400, weight=W_THIN)  # 日的中横
    g.hbar(330, 700, 200, weight=W_THIN)  # 日的底横
    return g


def build() -> list[Glyph]:
    """返回本 lane 的全部字形。"""
    return [
        glyph_long(),
        glyph_yi(),
        glyph_ai(),
        glyph_wu(),
        glyph_feng(),
        glyph_dian(),
        glyph_ji(),
        glyph_jian(),
    ]


def target_ufo() -> Path:
    return FONT_SRC / "masters" / "hkposter-cn.ufo"


if __name__ == "__main__":
    write_ufo(target_ufo(), build())
    print(f"[recipe] 已写出 {target_ufo()}")
