"""HK Poster Heavy —— Wave 0 高密字试制（lane: cjk-dense）。

字符清单（CONTRACT §5 冻结，不得增删）：
    龍 U+9F8D / 義 U+7FA9 / 警 U+8B66 / 愛 U+611B / 無 U+7121 / 道 U+9053

本 lane 的课题是「高密字的内白」（docs/02 内白、docs/03 GLY-006）。
坐标约定：y 向上、基线 0，字面框 y 0..820、x 60..940。
下文每个字的注释按「自上而下」的阅读顺序描述部件，坐标仍为 y 向上。

设计取舍记录
------------
1. 字面框统一 x 60..940、y 0..820（CONTRACT §2），advance 固定 1000。
2. 密度分层：笔画多且互相挤压的部位（龍的左半、義的羊部、警的言部、
   愛的夂部）用 84 / 76 的次级权重做**局部**减重（GLY-001 允许），
   开放式骨架（無的竖阵、道的首部）保持 96 / 92 的主次重量，
   避免整体缩细变成"普通黑体"（docs/02 偏差 A）。
3. 横向密排一律留白口：龍右半的横排间距 28 单位，警言部的横排间距
   10–24 单位（该字纵向层级最多，已到极限），其余字符的密排间距
   ≥ 20 单位。竖排内白（字腔）最小值 24 单位。
4. 笔画数与结构以权威字形（傳統字形結構）为准，不做"简化字"化处理：
   龍保留右半的「竖脊 + 七横 + 底钩」，警保留「敬(苟+攵) + 言」双部，
   無保留「丿 + 一 + 卌 + 一 + 一 + 灬」六层，愛保留爫/冖/心/夂四层。
5. 坐标全部取整；只使用 hkbuild 与标准库；recipe 为纯函数，生成物确定。
"""

from __future__ import annotations

import sys
from pathlib import Path

FONT_SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FONT_SRC / "scripts"))

from hkbuild import Glyph, write_ufo  # noqa: E402

# ---- 冻结权重（CONTRACT §2；76 仅用于高密字局部减重）----
W_MAIN = 96  # 主笔画
W_SEC = 92  # 次笔画
W_THIN = 84  # 细笔画（横杠 / 钩）
W_LIGHT = 76  # 局部减重（GLY-001 高频交叉与小空腔）


# ---------------------------------------------------------------------------
# 龍 U+9F8D —— 左「立 + 月」/ 右「竖脊 + 七横 + 底钩」
# ---------------------------------------------------------------------------
def glyph_long() -> Glyph:
    """龍。

    自上而下：
      左半（x 60..440）
        立 = 点(724..820) / 一(616..708) / 丷(508..604) / 一(396..488)
        月 = 横(288..380) / 内横(182..266) / 内横(82..166) + 两竖垂到底
        立部纵向只有 424 单位、四个笔画必然挤在一起，故：
          点用 88 宽的短点，不画成竖棍；
          丷用两个 slant 相反的 84 宽短点，与上下横各留 12 单位白口；
          月的两根内横用 84，与竖腿之间留 24 单位以上的字腔。
      右半（x 459..893）
        一条 92 粗的竖脊 + 七道 84 粗的横排，横排间距 28 单位，
        横 2 与横 3 之间加一个竖向节点（对应字形里的「コ」形），
        底横最长并向右出钩。
    """
    g = Glyph("uni9F8D", advance=1000, unicode=0x9F8D, note="龍（Wave 0 高密字）")

    # ---- 左半：立 ----
    g.dot(240, 772, w=88, h=96, slant=0)  # 立的点
    g.hbar(80, 420, 662, weight=W_SEC)  # 立的上横
    g.dot(172, 556, w=84, h=96, slant=-16)  # 立的下部左点（丶）
    g.dot(330, 556, w=84, h=96, slant=16)  # 立的下部右点（丿）
    g.hbar(60, 440, 442, weight=W_SEC)  # 立的下横

    # ---- 左半：月 ----
    g.hbar(120, 400, 334, weight=W_SEC)  # 月的上横
    g.diag(140, 320, 108, 60, weight=W_THIN)  # 月的左竖（略左倾）
    g.vbar(360, 380, 40, weight=W_SEC)  # 月的右竖
    g.hbar(150, 320, 224, weight=W_THIN)  # 月的第一内横
    g.hbar(150, 320, 124, weight=W_THIN)  # 月的第二内横

    # ---- 右半：竖脊 + 七横 + 底钩 ----
    g.vbar(505, 40, 790, weight=W_SEC)  # 竖脊
    g.hbar(465, 840, 754, weight=W_THIN)  # 横 1（最上）
    g.hbar(465, 830, 642, weight=W_THIN)  # 横 2
    g.vbar(720, 560, 620, weight=W_THIN)  # 横 2 与横 3 之间的竖向节点
    g.hbar(465, 830, 530, weight=W_THIN)  # 横 3
    g.hbar(465, 830, 418, weight=W_THIN)  # 横 4
    g.hbar(465, 830, 306, weight=W_THIN)  # 横 5
    g.hbar(465, 830, 194, weight=W_THIN)  # 横 6
    g.hbar(465, 880, 82, weight=W_THIN)  # 横 7（底横，最长）
    g.diag(845, 130, 765, 75, weight=W_THIN)  # 底横右端的出钩
    return g


# ---------------------------------------------------------------------------
# 義 U+7FA9 —— 上「羊」/ 下「我」
# ---------------------------------------------------------------------------
def glyph_yi() -> Glyph:
    """義。

    自上而下：
      羊部（y 428..820）
        丷(724..820) / 一(620..712) / 一(524..616) / 一(428..520) + 一竖贯穿
        三横间距 108 单位，竖两侧的字腔宽 100 单位以上，是本字最干净的内白。
      我部（y 16..440）
        手侧 = 丿 / 一(344..436) / 亅(20..344) / 提(44..156)
        戈侧 = 一(184..276) / ㇂ 斜钩(16..324) / 丿(129..210) / 丶(300..400)
      取舍：手的横与戈的横同属长横层，若都贴在一起会糊，故上下错开 100 单位；
      戈的撇用 76 做局部减重，使斜钩与撇的交叉处留出白口。
    """
    g = Glyph("uni7FA9", advance=1000, unicode=0x7FA9, note="義（Wave 0 高密字）")

    # ---- 羊 ----
    g.dot(320, 772, w=88, h=96, slant=-14)  # 丷 左
    g.dot(640, 772, w=88, h=96, slant=14)  # 丷 右
    g.hbar(100, 780, 666, weight=W_SEC)  # 横 1
    g.vbar(440, 430, 700, weight=W_THIN)  # 羊的竖
    g.hbar(140, 740, 570, weight=W_SEC)  # 横 2
    g.hbar(60, 780, 474, weight=W_SEC)  # 横 3

    # ---- 我：手侧 ----
    g.diag(430, 330, 350, 355, weight=W_LIGHT)  # 丿
    g.hbar(100, 420, 390, weight=W_SEC)  # 手的一
    g.vbar(280, 344, 20, weight=W_SEC)  # 亅
    g.diag(90, 50, 420, 100, weight=W_THIN)  # 提

    # ---- 我：戈侧 ----
    g.hbar(60, 740, 230, weight=W_SEC)  # 戈的一（长横）
    g.diag(545, 300, 745, 40, weight=W_THIN)  # ㇂ 斜钩
    g.diag(645, 200, 435, 140, weight=W_LIGHT)  # 丿（局部减重）
    g.dot(700, 350, w=84, h=100, slant=22)  # 丶
    return g


# ---------------------------------------------------------------------------
# 警 U+8B66 —— 上「敬」/ 下「言」
# ---------------------------------------------------------------------------
def glyph_jing() -> Glyph:
    """警。

    纵向层级最多的字：艹 + 句（含内口）+ 攵 + 言（丶 + 三横 + 口），
    共 9 道横。为守住内白：
      * 言部四道横全部用 76（GLY-001 局部减重），间距 10–24 单位；
      * 句内的口同样用 76，口内白 34 单位；
      * 言的口内白 36 单位，横 2 / 横 3 间距 10 单位——这是本字能给出的极限，
        再密就必然连成黑块，故用最轻权重而非压掉笔画。
    上部敬用 76–84：艹的竖 84，勹与攵的横 76，
    保证「艹 / 句 / 攵」三块之间还能看到白。
    """
    g = Glyph("uni8B66", advance=1000, unicode=0x8B66, note="警（Wave 0 高密字）")

    # ---- 敬：苟 ----
    g.hbar(90, 420, 772, weight=W_LIGHT)  # 艹的横
    g.vbar(180, 700, 820, weight=W_THIN)  # 艹的左竖
    g.vbar(330, 700, 820, weight=W_THIN)  # 艹的右竖
    g.hbar(100, 450, 688, weight=W_LIGHT)  # 勹的横
    g.vbar(410, 590, 690, weight=W_THIN)  # 勹的竖（横折钩）
    g.diag(200, 620, 135, 560, weight=W_LIGHT)  # 句的丿
    g.hbar(190, 340, 606, weight=W_LIGHT)  # 句内口的上横
    g.hbar(190, 340, 496, weight=W_LIGHT)  # 句内口的下横
    g.vbar(190, 534, 644, weight=W_LIGHT)  # 句内口的左竖
    g.vbar(340, 534, 644, weight=W_LIGHT)  # 句内口的右竖

    # ---- 敬：攵 ----
    g.diag(640, 720, 585, 630, weight=W_LIGHT)  # 攵的首撇
    g.hbar(500, 860, 698, weight=W_LIGHT)  # 攵的横
    g.diag(800, 700, 520, 470, weight=W_LIGHT)  # 乂的撇
    g.diag(570, 720, 840, 470, weight=W_LIGHT)  # 乂的捺

    # ---- 言 ----
    g.dot(470, 488, w=84, h=96, slant=14)  # 言的点
    g.hbar(60, 790, 408, weight=W_LIGHT)  # 言的长横
    g.hbar(170, 730, 322, weight=W_LIGHT)  # 言的横 2
    g.hbar(170, 730, 236, weight=W_LIGHT)  # 言的横 3
    g.hbar(170, 730, 150, weight=W_LIGHT)  # 言的横 4（口的上横）
    g.vbar(180, 38, 150, weight=W_LIGHT)  # 口的左竖
    g.vbar(720, 38, 150, weight=W_LIGHT)  # 口的右竖
    g.hbar(170, 730, 38, weight=W_LIGHT)  # 口的下横
    return g


# ---------------------------------------------------------------------------
# 愛 U+611B —— 上「爫」/ 中「冖 + 心」/ 下「夂」
# ---------------------------------------------------------------------------
def glyph_ai() -> Glyph:
    """愛。

    自上而下：
      爫 = 长撇(710..810) + 三点(622..718)
      冖 = 横(538..622) + 左垂(430..540) + 右垂(430..540)
      心 = 左点(425..525) + 中点(422..518) + 右点(420..520) + 卧钩(300..432)
      夂 = 横撇(232..308) + 乂的撇(98..252) + 乂的捺(37..127)
    取舍：爫的三点与冖的横贴得很近（8 单位），这是爫的固有节奏；
    心部压缩在 y 300..525 之间，用 84/76 保证两点与卧钩之间还能透出白；
    夂的长捺是全字唯一的出气口，故取 96 主笔画，
    让它把墨量拉到与 龍 / 警 同档，避免家族墨量率离散。
    """
    g = Glyph("uni611B", advance=1000, unicode=0x611B, note="愛（Wave 0 高密字）")

    # ---- 爫 ----
    g.diag(770, 805, 180, 715, weight=W_THIN)  # 爫的长撇
    g.dot(210, 670, w=84, h=96, slant=-14)  # 爫的点 1
    g.dot(460, 670, w=84, h=96, slant=-14)  # 爫的点 2
    g.dot(700, 670, w=84, h=96, slant=-14)  # 爫的点 3

    # ---- 冖 ----
    g.hbar(80, 860, 580, weight=W_MAIN)  # 冖的横
    g.vbar(120, 430, 540, weight=W_THIN)  # 冖的左垂
    g.vbar(820, 430, 540, weight=W_THIN)  # 冖的右垂

    # ---- 心 ----
    g.dot(210, 475, w=84, h=100, slant=-20)  # 心的左点
    g.dot(560, 470, w=76, h=96, slant=-10)  # 心的中点（局部减重）
    g.dot(700, 470, w=84, h=100, slant=20)  # 心的右点
    g.vbar(280, 300, 400, weight=W_THIN)  # 卧钩的竖
    g.hbar(280, 570, 390, weight=W_THIN)  # 卧钩的横

    # ---- 夂 ----
    g.hbar(160, 690, 270, weight=W_THIN)  # 夂的横撇
    g.diag(690, 240, 300, 110, weight=W_THIN)  # 乂的撇
    g.diag(380, 130, 850, 40, weight=W_MAIN)  # 乂的捺（出气口）
    return g


# ---------------------------------------------------------------------------
# 無 U+7121 —— 「丿 + 一 + 卌 + 一 + 一 + 灬」
# ---------------------------------------------------------------------------
def glyph_wu() -> Glyph:
    """無。

    自上而下：
      丿(717..813) / 一(634..726) / 四竖(240..640) / 一(434..526) / 一(234..326) / 灬(27..235)
    六层结构但纵向分布宽松，是本 lane 里最"透气"的字：
      * 四根竖（92）悬挂在横下并贯穿两道横，竖间的白口宽 80 单位以上；
      * 灬 四点画成向左下倾斜的短撇（84），彼此间距 220 单位，
        绝不会连成横画。
    墨量靠竖与横的 92 主重量拉齐家族中位。
    """
    g = Glyph("uni7121", advance=1000, unicode=0x7121, note="無（Wave 0 高密字）")

    g.diag(290, 790, 205, 740, weight=W_THIN)  # 顶部的短撇
    g.hbar(140, 810, 680, weight=W_SEC)  # 上横
    g.vbar(220, 240, 640, weight=W_SEC)  # 竖 1
    g.vbar(395, 240, 640, weight=W_SEC)  # 竖 2
    g.vbar(570, 240, 640, weight=W_SEC)  # 竖 3
    g.vbar(745, 240, 640, weight=W_SEC)  # 竖 4
    g.hbar(80, 820, 480, weight=W_SEC)  # 中横
    g.hbar(60, 860, 280, weight=W_SEC)  # 下横

    # 灬：四撇，各自独立
    g.diag(210, 195, 150, 65, weight=W_THIN)
    g.diag(430, 195, 370, 65, weight=W_THIN)
    g.diag(640, 195, 580, 65, weight=W_THIN)
    g.diag(830, 195, 770, 65, weight=W_THIN)
    return g


# ---------------------------------------------------------------------------
# 道 U+9053 —— 左「辶」/ 右「首」
# ---------------------------------------------------------------------------
def glyph_dao() -> Glyph:
    """道。

    包围结构：辶在左下（撇点 + 横折折撇），平捺作为全字底边
    从 x 117 拉到 x 863，是本字的"落地线"。
    首部（x 298..842）：丷(722..818) + 一(614..706) + 目。
    目为四横两竖，三道内白高 34–48 单位，是全 lane 最干净的内白。
    取舍：目的横竖用 84（细横杠）而丷与首的一用 92，
    使包围结构的"框"与"内容"有对比（GLY-001）。
    """
    g = Glyph("uni9053", advance=1000, unicode=0x9053, note="道（Wave 0 高密字）")

    # ---- 首 ----
    g.dot(340, 770, w=84, h=96, slant=-16)  # 丷 左
    g.dot(660, 770, w=84, h=96, slant=16)  # 丷 右
    g.hbar(330, 860, 660, weight=W_SEC)  # 首的一
    g.hbar(400, 840, 560, weight=W_THIN)  # 目的上横
    g.vbar(440, 20, 580, weight=W_THIN)  # 目的左竖
    g.vbar(800, 20, 580, weight=W_THIN)  # 目的右竖
    g.hbar(440, 800, 420, weight=W_THIN)  # 目的内横 1
    g.hbar(440, 800, 290, weight=W_THIN)  # 目的内横 2
    g.hbar(400, 840, 170, weight=W_THIN)  # 目的下横

    # ---- 辶 ----
    g.dot(160, 760, w=84, h=110, slant=-26)  # 辶的撇点
    g.hbar(70, 290, 580, weight=W_THIN)  # 辶的横
    g.diag(240, 520, 150, 400, weight=W_THIN)  # 横折折撇的上段
    g.hbar(60, 260, 340, weight=W_THIN)  # 横折折撇的下横
    g.diag(230, 280, 160, 120, weight=W_THIN)  # 横折折撇的撇
    g.diag(130, 50, 860, 80, weight=W_SEC)  # 平捺（落地线）
    return g


def build() -> list[Glyph]:
    """返回本 lane 的全部字形。"""
    return [
        glyph_long(),
        glyph_yi(),
        glyph_jing(),
        glyph_ai(),
        glyph_wu(),
        glyph_dao(),
    ]


def target_ufo() -> Path:
    return FONT_SRC / "masters" / "hkposter-cjk-dense.ufo"


if __name__ == "__main__":
    write_ufo(target_ufo(), build())
    print(f"[recipe] 已写出 {target_ufo()}")
