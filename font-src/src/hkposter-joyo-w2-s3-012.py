def hband(g, x1, x2, y_top, y_bot):
    """横画：给墨迹上下缘，中心线内缩半个笔画宽。"""
    g.hbar(x1, x2, (y_top + y_bot) / 2.0, weight=y_top - y_bot)


def vband(g, x_left, x_right, y_bot, y_top):
    """竖画：给墨迹左右缘与上下端点。"""
    g.vbar((x_left + x_right) / 2.0, y_bot, y_top, weight=x_right - x_left)


def dot(g, cx, cy, w=W_DOT, h=96, slant=-14):
    """点/短撇：斜切平行四边形。slant 只用 0 / -14 / +14 / 26。"""
    g.dot(cx, cy, w=w, h=h, slant=slant)


def stroke_path(g, pts, weight=84):
    """折线按笔宽生成外轮廓多边形（平接转角），用于卧钩/弯钩这类曲线。
    曲线用折线近似比用几段 diag 拼接更接近标准骨架的走势。"""
    hw = weight / 2.0
    normals = []
    for i in range(len(pts) - 1):
        dx = pts[i + 1][0] - pts[i][0]
        dy = pts[i + 1][1] - pts[i][1]
        length = math.hypot(dx, dy)
        normals.append((-dy / length, dx / length))
    left, right = [], []
    for i, (x, y) in enumerate(pts):
        if i == 0:
            nx, ny = normals[0]
        elif i == len(pts) - 1:
            nx, ny = normals[-1]
        else:
            ax, ay = normals[i - 1]
            bx, by = normals[i]
            nx, ny = ax + bx, ay + by
            length = math.hypot(nx, ny) or 1.0
            nx, ny = nx / length, ny / length
            scale = 1.0 / max(0.40, nx * ax + ny * ay)
            nx, ny = nx * scale, ny * scale
        left.append((x + nx * hw, y + ny * hw))
        right.append((x - nx * hw, y - ny * hw))
    g.poly(left + right[::-1])


