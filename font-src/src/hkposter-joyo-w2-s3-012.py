def sanzui(g, x0, y0, x1, y1):
    """氵（左三点水）：上点（短撇 26）+ 中点（丶 -14）+ 提。
    box = (left, bottom, right, top) 的墨迹范围。"""
    w = x1 - x0
    h = y1 - y0
    dot(g, x0 + 0.40 * w, y1 - 0.14 * h, w=84, h=104, slant=26)   # 上点
    dot(g, x0 + 0.58 * w, y1 - 0.52 * h, w=84, h=96, slant=-14)   # 中点
    g.diag(x0 + 0.06 * w, y0 + 0.22 * h, x0 + 0.80 * w, y0 + 0.46 * h, weight=84)


def tehen(g, x0, x1, y_top, y_bot):
    """扌（左提手旁）：一 / 亅 / 提。x0..x1 为墨迹左右缘。"""
    hband(g, x0, x1, y_top, y_top - 84)                      # 横
    vband(g, x0 + 106, x0 + 190, y_bot + 96, y_top + 84)     # 竖
    g.diag(x0 + 150, y_bot + 96, x0 + 62, y_bot + 44, weight=84)   # 竖钩的钩
    g.diag(x0 + 8, y_bot + 62, x1 - 12, y_bot + 168, weight=84)    # 提


def kokoro(g, x0, y0, x1, y1):
    """心：左点 + 卧钩（折线）+ 中点 + 右点。
    box = (left, bottom, right, top) 的墨迹范围。"""
    w = x1 - x0
    h = y1 - y0
    stroke_path(g, [
        (x0 + 0.10 * w, y0 + 0.46 * h),
        (x0 + 0.26 * w, y0 + 0.14 * h),
        (x0 + 0.54 * w, y0 + 0.07 * h),
        (x0 + 0.78 * w, y0 + 0.20 * h),
        (x0 + 0.88 * w, y0 + 0.52 * h),
    ], 84)
    dot(g, x0 + 0.05 * w, y0 + 0.66 * h, w=84, h=92, slant=-14)   # 左点
    dot(g, x0 + 0.40 * w, y0 + 0.84 * h, w=84, h=92, slant=-14)   # 中点
    dot(g, x0 + 0.80 * w, y0 + 0.62 * h, w=84, h=92, slant=-14)   # 右点


def bi(g, x0, y0, x1, y1):
    """必：ノ（长撇）+ 卧钩（折线）+ 三点。
    box = (left, bottom, right, top) 的墨迹范围。"""
    w = x1 - x0
    h = y1 - y0
    g.diag(x0 + 0.74 * w, y0 + 0.96 * h, x0 + 0.12 * w, y0 + 0.14 * h, weight=84)
    stroke_path(g, [
        (x0 + 0.22 * w, y0 + 0.34 * h),
        (x0 + 0.54 * w, y0 + 0.06 * h),
        (x0 + 0.82 * w, y0 + 0.16 * h),
        (x0 + 0.90 * w, y0 + 0.42 * h),
    ], 84)
    dot(g, x0 + 0.06 * w, y0 + 0.60 * h, w=84, h=88, slant=-14)
    dot(g, x0 + 0.34 * w, y0 + 0.74 * h, w=84, h=88, slant=-14)
    dot(g, x0 + 0.92 * w, y0 + 0.58 * h, w=84, h=88, slant=-14)


def nogi(g, x0, x1, y_top, y_bot):
    """禾：ノ + 一 + 丨 + ノ + 乀。x0..x1 为墨迹左右缘。"""
    g.diag(x1 - 20, y_top, x0 + 90, y_top - 110, weight=84)      # 顶撇
    hband(g, x0, x1, y_top - 150, y_top - 234)                   # 横
    vband(g, x0 + 118, x0 + 202, y_bot, y_top - 60)              # 竖
    g.diag(x0 + 176, y_top - 250, x0 + 12, y_bot + 90, weight=84)   # 撇
    g.diag(x0 + 166, y_top - 290, x1 - 16, y_bot + 40, weight=84)   # 捺


