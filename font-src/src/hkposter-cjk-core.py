def glyph_ye() -> Glyph:
    """夜。

    上中下结构：亠(662..840) / 左亻(60..450) / 右夂+点(120..830)。
    取舍：亠占顶 180 单位独占一层；亻的撇与竖在 (180..240, 398..450) 交汇，
      保证左侧不是一个飘空的撇；夂的横撇与捺分列，内白不粘连。
    返工（2026-10-26，docs/10 §7-1「夂的横撇与捺偏近」）：
      旧版夂的横 (560..830 @590) 与捺起笔 (560,500) 只差 4 单位（几乎粘连），
      且「横折钩」的撇段从 x=710 起笔而横的右端在 830 —— 两者**不连续**，
      违背「横撇是一条笔」的骨架。
      照标准骨架（参照 Zen Kaku Gothic New Black 的「夜」）改：
      - 夂的横撇改为**一条连续笔**：横 545..860 @620，撇段从横的右端 (860,620)
        折向左下到 (665,430)；
      - 捺的起笔移到 (520,430)（横的左端下方），与撇段终点余隙 53；
      - 夂的上撇缩短，避免与捺起笔相碰。
      校验：横下缘 574 与捺起笔上缘 478 → 余隙 96；
        撇段墨 639..732 与捺起笔墨 474..566 → 余隙 53。
    """
    g = Glyph("uni591C", advance=1000, unicode=0x591C, note="夜：（Wave0代表字形，2026-10-26返工）")

    # ---- 亠 ----
    # 2026-10-31 回修：亠的横原来中心线 710（墨 662..758），与夂的横
    # 620（墨 574..666）白口 −4 —— 两者糊成一条黑带，整个上半部没有白。
    # 参照 M PLUS 1p Black「夜」实测：亠横与夂横相距约 205 单位。
    # 改为：亠横上移到 740（墨 692..788）、点上移到 800（墨 762..838），
    # 夂的横下移到 600（墨 554..646）→ 白口 46。
    g.dot(500, 800, w=76, h=76, slant=0)       # 亠的点（墨 762..838）
    g.hbar(100, 900, 740, weight=W_MAIN)       # 亠的横（墨 692..788）

    # ---- 亻 ----
    g.diag(330, 690, 180, 420, weight=W_SEC)   # 亻的撇（起笔压住亠的横）
    g.vbar(240, 450, 60, weight=W_SEC)         # 亻的竖

    # ---- 夂 + 点 ----
    g.diag(700, 668, 580, 545, weight=W_SEC)   # 夂的撇（起笔压住亠的横）
    g.hbar(545, 860, 600, weight=W_SEC)        # 夂的横（墨 554..646）
    g.diag(860, 600, 665, 410, weight=W_SEC)   # 夂的横撇下行（从横的右端折下）
    g.diag(520, 410, 900, 60, weight=W_MAIN)   # 夂的捺（起笔在撇段下方）
    g.dot(880, 250, w=74, h=82, slant=18)     # 右下点
    return g


def glyph_feng() -> Glyph:
    """風。

    包围结构：几外框(120..938) + 内部「虫」(300..700)。
    取舍：外框用 92（比主笔画略细），让"框"与"内容"有对比；
      几的左撇与右竖带冲出，弯钩向右下收笔，不做满包围。
    返工（2026-10-26，docs/10 §7-1「内部虫部偏挤」）：
      旧版虫的口只有 x 330..690 / y 390..620（宽 360 高 230），
      在 820 高的外框里显得缩在中间偏上，且虫的中竖与口的左右竖间距只有 56。
      照标准骨架（参照 Zen Kaku Gothic New Black 的「風」）把虫部放大并下移：
      - 口放大到 x 280..690 / y 280..520（宽 410 高 240），与参照的虫部占位一致；
      - 口内白：中竖墨 443..527，距口左竖内缘 364 有 79、距右竖内缘 606 有 79；
      - 虫的中竖贯穿口并出头到 y=530，提与竖底相接。
      校验：口左缘 238 与几的左撇墨（99..191）余隙 47；
        口右缘 732 与几的右竖墨（809..901）余隙 77。
    """
    g = Glyph("uni98A8", advance=1000, unicode=0x98A8, note="風：（Wave0代表字形，2026-10-26返工）")

    # ---- 几 ----
    g.hbar(180, 880, 790, weight=W_SEC)        # 几的顶横
    g.diag(215, 800, 115, 60, weight=W_SEC)    # 几的左撇
    g.vbar(855, 800, 210, weight=W_SEC)        # 几的右竖
    g.diag(855, 210, 940, 125, weight=W_THIN)  # 几的弯钩

    # ---- 虫 ----
    g.hbar(280, 690, 520, weight=W_THIN)       # 虫的口上横（返工：放大）
    g.vbar(322, 520, 280, weight=W_THIN)       # 虫的口左竖
    g.vbar(648, 520, 280, weight=W_THIN)       # 虫的口右竖
    g.hbar(280, 690, 280, weight=W_THIN)       # 虫的口下横
    g.vbar(485, 530, 80, weight=W_THIN)        # 虫的竖（返工：出头）
    g.hbar(300, 660, 80, weight=W_THIN)        # 虫的提
    g.dot(715, 250, w=74, h=82, slant=16)      # 虫的点（返工：右移）
    return g


def build() -> list[Glyph]:
    # 火（U+706B）不在本 lane：它同时属于 Jōyō 常用漢字集合，
    # 由 wave1/joyo-s1-003 批次提供。
    # 一个码位在一个字体里只能有一个字形，两边都做会在合成时撞码；
    # 本文件曾留的独立「火」实现是**死代码**，2026-10-26 已删除（见上方说明）。
    return [
        glyph_gang(),
        glyph_ying(),
        glyph_cheng(),
        glyph_ye(),
        glyph_feng(),
    ]


def target_ufo() -> Path:
    return FONT_SRC / "masters" / "hkposter-cjk-core.ufo"


if __name__ == "__main__":
    write_ufo(target_ufo(), build())
    print(f"[recipe] 已写出 {target_ufo()}")
