"""HK Poster Heavy —— Wave 0 汉字试制（lane: cjk-core）。

字符清单（CONTRACT §5 冻结）：
    港 U+6E2F / 影 U+5F71 / 城 U+57CE / 火 U+706B / 夜 U+591C / 風 U+98A8

方法（与 cjk-dense lane 同法）：每个字先写笔画清单与部件分区坐标，
再逐笔画落坐标并注明所属部件；密排处留白口，疏字用足笔画重量。

CJK 字面顶线 = 820（Latin 大写顶线是 700，两套各自成立）。
"""

from __future__ import annotations

import sys
from pathlib import Path

FONT_SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FONT_SRC / "scripts"))

from hkbuild import Glyph, write_ufo  # noqa: E402

W_MAIN = 96
W_SEC = 92
W_THIN = 84
W_HAIR = 76

CJK_TOP = 820


def glyph_gang() -> Glyph:
    """港。

    左右结构：氵(x 38..250) + 巷(x 300..940)。
    巷分两层：共(480..838) / 巳(4..466)，两层之间留白口 14 单位以上。
    取舍：巷笔画密集，整体降到 84（横 96 保留骨架），让墨量率不压过同族；
      巳的左竖与底弯钩连成一体，保住「己」形识别；氵的两点用 94 宽。
    """
    g = Glyph("uni6E2F", advance=1000, unicode=0x6E2F, note="港：（Wave0代表字形）")

    # ---- 氵 ----
    g.dot(158, 700, w=94, h=126, slant=26)      # 氵的上点
    g.dot(150, 468, w=94, h=126, slant=26)      # 氵的下点
    g.diag(70, 140, 248, 308, weight=92)       # 氵的提

    # ---- 共 ----
    g.hbar(330, 920, 790, weight=W_MAIN)       # 共的上横
    g.vbar(450, 830, 640, weight=W_THIN)       # 共的左竖
    g.vbar(810, 830, 640, weight=W_THIN)       # 共的右竖
    g.hbar(300, 940, 640, weight=W_MAIN)       # 共的下横
    g.diag(650, 600, 420, 480, weight=W_HAIR)   # 共的撇
    g.dot(745, 552, w=84, h=96, slant=26)      # 共的点

    # ---- 巳 ----
    g.hbar(370, 880, 420, weight=W_THIN)       # 巳的上横
    g.vbar(880, 420, 280, weight=W_THIN)       # 巳的右竖
    g.hbar(370, 880, 280, weight=W_THIN)       # 巳的中横
    g.vbar(370, 420, 50, weight=W_THIN)        # 巳的左竖
    g.hbar(370, 880, 50, weight=W_THIN)        # 巳的底横
    g.vbar(880, 50, 140, weight=W_HAIR)        # 巳的钩
    return g


def glyph_ying() -> Glyph:
    """影。

    左右结构：景(x 60..600) + 彡(x 660..940)。
    景自上而下：日(528..820) / 亠(406..498) / 口(186..378) / 小(40..170)。
    取舍：日与亠之间留 30 单位、亠与口之间留 28 单位、口与小之间留 16 单位；
      日的两个腔各留 24 单位白口、口腔留 24 单位白口（AGENTS.md 铁律 10）；
      彡三撇自上而下等距（每撇落差 190），彼此不相接。
    """
    g = Glyph("uni5F71", advance=1000, unicode=0x5F71, note="影：（Wave0代表字形）")

    # ---- 景上部：日 ----
    # 2026-10-31 回修：日的三横原来中心线 778/700/620、墨迹 736..820 / 662..738 /
    # 578..662 —— 相邻白口 −2 / 0，两个日腔被封死，渲染出来是黑砖。
    # 改为：上横 778（W_THIN，墨 736..820）、中横 674（W_HAIR，墨 636..712）、
    # 下横 570（W_THIN，墨 528..612）→ 两处白口各 24。
    # 参照 M PLUS 1p Black「影」实测：日槽高 24 单位、宽 199 单位 ——
    # 槽高 24 与本仓门槛一致；本字把日做宽到 x 180..460、竖用 W_HAIR，
    # 内白宽 128（参照 199，海报体更厚，窄一些是风格取舍）。
    g.hbar(180, 460, 778, weight=W_HAIR)       # 日的上横（墨 736..820）
    g.vbar(218, 778, 570, weight=W_HAIR)       # 日的左竖（墨 x 180..256）
    g.vbar(422, 778, 570, weight=W_HAIR)       # 日的右竖（墨 x 384..460）
    g.hbar(180, 460, 674, weight=W_HAIR)       # 日的中横（墨 636..712）
    g.hbar(180, 460, 570, weight=W_HAIR)       # 日的下横（墨 528..612）

    # ---- 景：亠 ----
    g.dot(300, 520, w=76, h=70, slant=0)       # 亠的点（墨 485..555，压住日下横）
    g.hbar(80, 520, 452, weight=W_SEC)         # 亠的横（墨 406..498，白口 30）

    # ---- 景：口 ----
    # 口放大到 x 175..465、竖用 W_HAIR → 内白宽 138（参照 M PLUS「影」口槽宽 174）
    g.hbar(175, 465, 336, weight=W_HAIR)       # 口的上横（墨 294..378）
    g.vbar(213, 336, 228, weight=W_HAIR)       # 口的左竖（墨 x 175..251）
    g.vbar(427, 336, 228, weight=W_HAIR)       # 口的右竖（墨 x 389..465）
    g.hbar(175, 465, 228, weight=W_HAIR)       # 口的下横（墨 186..270）  # HC_SELFTEST_ANCHOR

    # ---- 景下部：小 ----
    # 小字头的标准骨架：左点为撇（"/"）、右点为捺（"\\"）。
    # slant 是平行四边形「顶部右移」量：正 slant = 顶部右移 = 撇向（"/"），
    # 负 slant = 顶部左移 = 捺向（"\\"）。
    # 实测参照（M PLUS 1p Black「少」U+5C11）：左侧两点 top-bottom x 偏移
    # = +155.0（"/"）与 −197.5（"\\"）—— 确证左撇右捺。
    # 2026-10-27 返工：原先左右写反（左 −14 / 右 +14 = 捺/撇，镜像）。
    g.vbar(300, 170, 40, weight=W_SEC)         # 小的竖（墨 40..170）
    g.dot(190, 115, w=72, h=80, slant=14)       # 小的左点（撇，"/"）
    g.dot(410, 115, w=72, h=80, slant=-14)      # 小的右点（捺，"\\")

    # ---- 彡 ----
    g.diag(900, 780, 690, 660, weight=W_THIN)  # 彡的第一撇
    g.diag(900, 590, 690, 470, weight=W_THIN)  # 彡的第二撇
    g.diag(900, 400, 680, 240, weight=W_THIN)  # 彡的第三撇
    return g


def glyph_cheng() -> Glyph:
    """城。

    左右结构：土(x 60..350) + 成(x 390..945)。
    成自上而下：顶横 / 撇 / 横折钩 / 斜钩 / 内撇 / 点。
    取舍（2026-10-26 返工，docs/10 §7-1「横折钩与斜钩偏近」）：
      旧版斜钩起点在 (660,760) —— 既**悬在顶横上方**（顶横上缘 738），
      又在 y=430 处正好压到横折钩的竖（x=790）上，中部糊成一片。
      照标准骨架（参照 Zen Kaku Gothic New Black 的「城」，SIL OFL 1.1）改：
      - 斜钩起笔移到 x=660 且**接住顶横**（起笔点 y=690 落进顶横墨内
        672±48；注意斜笔的墨迹沿垂直于中心线展开，y 方向只有 ±18，
        不能按水平笔画那样按 ±46 估）；
      - 横折钩整体左移（横 510..660、竖 x=660），斜钩从它**右侧**冲过；
      - 参照字里斜钩与横折钩**完全不相交**，这一点必须守住；
      - 内撇右移到 x=810，避让斜钩。
      校验：y=430 处斜钩墨 725..809，竖墨 614..706 → 余隙 19；
        y=250（竖底）处斜钩墨 799..883，与竖余隙 93；内撇起笔与斜钩余隙 15。
    """
    g = Glyph("uni57CE", advance=1000, unicode=0x57CE, note="城：（Wave0代表字形，2026-10-26返工）")

    # ---- 土 ----
    g.hbar(90, 320, 570, weight=W_SEC)         # 土的横
    g.vbar(205, 700, 90, weight=W_SEC)         # 土的竖
    g.hbar(60, 350, 130, weight=W_MAIN)        # 土的提

    # ---- 成 ----
    g.hbar(430, 896, 672, weight=W_MAIN)       # 成的顶横
    g.diag(520, 655, 410, 80, weight=W_SEC)    # 成的左撇
    g.hbar(510, 660, 430, weight=W_SEC)        # 成的横折钩横
    g.vbar(660, 430, 250, weight=W_SEC)        # 成的横折钩竖
    g.diag(660, 690, 915, 70, weight=W_SEC)    # 成的斜钩（返工：起笔接住顶横、从横折钩右侧冲过）
    g.diag(915, 70, 938, 115, weight=W_HAIR)   # 成的钩尾
    g.diag(810, 545, 665, 355, weight=W_THIN)  # 成的内撇（返工：右移避让斜钩）
    g.dot(885, 785, w=84, h=92, slant=20)      # 成的点
    return g


