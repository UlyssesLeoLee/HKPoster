# 小假名落位：水平居中（墨迹外接框中心 x=500）+ 贴基线（底边 y=40）。
# 参照**开源**参照字体的实测落位（M PLUS 1p Black：12 个小假名中心 x 482..530
# / 1000 em，底边与全尺寸字同在基线上）。**只平移，不改形状**：
# 笔画清单、笔画拆法、相对坐标一律不动，落位靠一次整体平移完成。
SMALL_PLACE_CX = 500.0
SMALL_PLACE_BOTTOM = 40.0

# 个别小假名的**尺寸**修正（v2 规格任务 B2 / v3 沿用）：
# ゖ 现状字高 416 = 全尺寸假名的 0.55，卡在「小假名/全尺寸假名 ≥ 0.55」
# 的门槛上；标准小假名应在 0.65..0.72。
# ょ/ゕ/ぉ 原本在「0.60..0.80」这条设计线上；全尺寸假名加粗后字高中位
# 从 774 涨到 785.5，它们的比例被摊薄到 0.558..0.589 —— 按同样办法补回。
# 做法 = 只放大中心线坐标（笔画权重不动、不改笔画拆法），
# 再交给 `_place_small` 重新落位（水平居中 + 贴基线）。
SMALL_SCALE = {
    "ゖ": 1.30,
    "ょ": 1.14,
    "ゕ": 1.07,
    "ぉ": 1.06,
}


def _place_small(strokes):
    """把小假名平移到「水平居中 + 贴基线」的位置（只平移，不改形状）。

    平移量取整：中心线坐标本来都是整数，整数平移在浮点上是精确的，
    因此加粗出来的轮廓与平移前**逐点完全相同**（形状零改动）。
    """
    bb = _measure(strokes)
    if bb is None:
        return list(strokes)
    dx = int(round(SMALL_PLACE_CX - (bb[0] + bb[2]) / 2.0))
    dy = int(round(SMALL_PLACE_BOTTOM - bb[1]))
    return _map_strokes(strokes, lambda x, y: (x + dx, y + dy))

