def _measure(strokes):
    """走一遍 hkbuild，量出这组笔画的墨迹外接框 (x0, y0, x1, y1)。"""
    g = Glyph("uni0000", advance=1000)
    for s in strokes:
        _stroke(g, s)
    xs = []
    ys = []
    for contour in g.contours():
        for pt in contour:
            xs.append(pt[0])
            ys.append(pt[1])
    if not xs:
        return None
    return (min(xs), min(ys), max(xs), max(ys))


def _map_strokes(strokes, fn):
    """把笔画描述里的**中心线坐标**过一遍 fn(x, y) -> (x, y)。

    笔画权重（weight / w / h / slant）一律不动——放大只放大骨架。
    """
    out = []
    for s in strokes:
        kind = s[0]
        if kind == "h":
            _, x1, x2, y, w = s
            nx1, ny1 = fn(x1, y)
            nx2, ny2 = fn(x2, y)
            out.append(("h", nx1, nx2, ny1, w))
        elif kind == "v":
            _, x, y1, y2, w = s
            nx, ny1 = fn(x, y1)
            _, ny2 = fn(x, y2)
            out.append(("v", nx, ny1, ny2, w))
        elif kind == "d":
            _, x1, y1, x2, y2, w = s
            n1 = fn(x1, y1)
            n2 = fn(x2, y2)
            out.append(("d", n1[0], n1[1], n2[0], n2[1], w))
        elif kind == "p":
            _, pts, w = s
            out.append(("p", [fn(x, y) for x, y in pts], w))
        elif kind == "dot":
            _, cx, cy, w, h, slant = s
            n = fn(cx, cy)
            out.append(("dot", n[0], n[1], w, h, slant))
        elif kind == "ring":
            _, outer, inner = s
            out.append(("ring", [fn(x, y) for x, y in outer],
                        [fn(x, y) for x, y in inner]))
        else:
            raise ValueError(f"未知笔画类型：{kind!r}")
    return out


def _offset_strokes(strokes, dx=0.0, dy=0.0):
    """整体平移（给浊音符让位时用）。"""
    if not dx and not dy:
        return list(strokes)
    return _map_strokes(strokes, lambda x, y: (x + dx, y + dy))


def _narrow_strokes(strokes, k, anchor_x):
    """横向收窄：只缩放 x 坐标（**高度与笔画权重一律不动**），锚点为 anchor_x。"""
    if abs(k - 1.0) < 1e-9:
        return list(strokes)
    return _map_strokes(strokes, lambda x, y: (anchor_x + (x - anchor_x) * k, y))


def _narrow_to_fit(base_strokes, mark_strokes, margin=5.0):
    """底座横向收窄到「刚好不碰浊音符」，并返回收窄后的笔画与让位偏移。

    参照字体的做法（开源参照 M PLUS 1p Black：せ x 57..942，ぜ x 47..990；
    Noto Sans JP Black：せ x 53..915，ぜ x 34..953）：
    浊点占住右上角，浊音形的底座必然比单独的全尺寸字窄。
    这里以底座**左缘**为锚点只收右边（高度与权重不动），
    二分出「底座右缘刚好退到浊音符左边（留 margin 余量）」的最大收窄系数。
    """
    bb = _measure(base_strokes)
    mb = _measure(mark_strokes)
    if bb is None or mb is None:
        return list(base_strokes), 0.0
    anchor = bb[0]
    limit = mb[0] - margin
    lo, hi = 0.0, 1.0
    for _ in range(20):
        mid = (lo + hi) / 2.0
        probe = _measure(_narrow_strokes(base_strokes, mid, anchor))
        if probe is not None and probe[2] <= limit:
            lo = mid
        else:
            hi = mid
    narrowed = _narrow_strokes(base_strokes, lo, anchor)
    nb = _measure(narrowed)
    dx = 0.0
    if nb is not None and nb[0] < INK_X[0]:
        dx = INK_X[0] - nb[0]
    return narrowed, dx


def _scale_only(strokes, k):
    """只缩放**中心线坐标**（笔画权重不动），围绕这组笔画自身的墨迹外接框中心。

    与 `_scale_strokes` 的区别：不做「对到 (500, 400)」的对齐，
    也不做框夹取 —— 只把一组已经按最终空间画好的笔画整体放大，
    落位仍交给 `_place_small`（水平居中 + 贴基线）。
    """
    bb = _measure(strokes)
    if bb is None:
        return list(strokes)
    cx = (bb[0] + bb[2]) / 2.0
    cy = (bb[1] + bb[3]) / 2.0
    return _map_strokes(strokes, lambda x, y: ((x - cx) * k + cx, (y - cy) * k + cy))


def _scale_once(strokes, k):
    """按系数 k 缩放中心线，并把墨迹外接框中心对到 (500, 400)。"""
    bb0 = _measure(strokes)
    if bb0 is None:
        return list(strokes)
    cx = (bb0[0] + bb0[2]) / 2.0
    cy = (bb0[1] + bb0[3]) / 2.0
    scaled = _map_strokes(strokes, lambda x, y: ((x - cx) * k, (y - cy) * k))
    bb1 = _measure(scaled)
    if bb1 is None:
        return scaled
    dx = CENTER_X - (bb1[0] + bb1[2]) / 2.0
    dy = CENTER_Y - (bb1[1] + bb1[3]) / 2.0
    return _map_strokes(scaled, lambda x, y: (x + dx, y + dy))


def _fits(bb):
    """墨迹尺寸是否装得进字面框。"""
    return ((bb[2] - bb[0]) <= (INK_X[1] - INK_X[0]) + 0.5
            and (bb[3] - bb[1]) <= (INK_Y[1] - INK_Y[0]) + 0.5)


def _scale_strokes(strokes, k=KANA_SCALE):
    """把一组笔画放大到与汉字同族。

    * 只缩放中心线坐标，笔画权重不动；
    * 围绕该字自身的墨迹外接框中心缩放；
    * 缩放后把墨迹外接框中心重新对到 (500, 400)；
    * 放大后装不进 x 60..940 / y 0..820 字面框的字，
      系数收敛到「刚好装下」的上限（只此一字例外，形状不改）；
    * 仍越框时只整体平移，不改形状。
    """
    scaled = _scale_once(strokes, k)
    bb = _measure(scaled)
    if bb is None:
        return scaled
    if not _fits(bb):
        lo, hi = 0.0, k
        for _ in range(18):
            mid = (lo + hi) / 2.0
            probe = _measure(_scale_once(strokes, mid))
            if probe is not None and _fits(probe):
                lo = mid
            else:
                hi = mid
        scaled = _scale_once(strokes, lo)
        bb = _measure(scaled)
        if bb is None:
            return scaled
    sx = 0.0
    sy = 0.0
    if bb[0] < INK_X[0]:
        sx = INK_X[0] - bb[0]
    elif bb[2] > INK_X[1]:
        sx = INK_X[1] - bb[2]
    if bb[1] < INK_Y[0]:
        sy = INK_Y[0] - bb[1]
    elif bb[3] > INK_Y[1]:
        sy = INK_Y[1] - bb[3]
    if sx or sy:
        scaled = _map_strokes(scaled, lambda x, y: (x + sx, y + sy))
    return scaled


