def build() -> list[Glyph]:
    glyphs: list[Glyph] = []

    # 基础 46
    for ch in BASE_ORDER:
        g = Glyph(f"uni{CP[ch]:04X}", advance=1000, unicode=CP[ch], note=f"平假名 {ch}（基础形）")
        for s in KANA[ch]:
            _stroke(g, s)
        glyphs.append(g)

    # 预组合 25（浊音 / 半浊音）
    for ch, base, dx, dy, mark in VOICED_ORDER:
        g = Glyph(f"uni{CP[ch]:04X}", advance=1000, unicode=CP[ch], note=f"平假名 {ch}（{base} + 浊音）")
        for s in KANA[base]:
            _stroke(g, s, dx, dy)
        for s in (DAKU if mark == "daku" else HAND):
            _stroke(g, s)
        glyphs.append(g)

    # 浊音符 U+3099（零宽合记号）
    g = Glyph("uni3099", advance=0, unicode=0x3099, note="浊音符（零宽合记号，右上角两枚短斜画）")
    for s in DAKU:
        _stroke(g, s)
    glyphs.append(g)

    # 半浊音符 U+309A（零宽合记号）
    g = Glyph("uni309A", advance=0, unicode=0x309A, note="半浊音符（零宽合记号，右上角小圆环）")
    for s in HAND:
        _stroke(g, s)
    glyphs.append(g)

    # 浊点符号 U+309B / U+309C（独立形，advance 1000）
    g = Glyph("uni309B", advance=1000, unicode=0x309B, note="浊点符号 ゛（独立形）")
    for s in DAKU:
        _stroke(g, s)
    glyphs.append(g)

    g = Glyph("uni309C", advance=1000, unicode=0x309C, note="浊点符号 ゜（独立形）")
    for s in HAND:
        _stroke(g, s)
    glyphs.append(g)

    # 反复记号 U+309D / U+309E
    g = Glyph("uni309D", advance=1000, unicode=0x309D, note="反复记号 ゝ（上一字形的缩小重复形）")
    for s in ITER:
        _stroke(g, s)
    glyphs.append(g)

    g = Glyph("uni309E", advance=1000, unicode=0x309E, note="反复记号 ゞ（缩小重复形 + 浊音符）")
    for s in ITER:
        _stroke(g, s)
    for s in DAKU:
        _stroke(g, s)
    glyphs.append(g)

    return glyphs


