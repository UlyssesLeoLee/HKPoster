def build() -> list[Glyph]:
    glyphs: list[Glyph] = []

    # 基础 48（全尺寸；放大 ×1.35 到与汉字同族）
    for ch in BASE_ORDER:
        g = Glyph(f"uni{CP[ch]:04X}", advance=1000, unicode=CP[ch], note=f"平假名 {ch}（基础形）")
        for s in _scale_strokes(KANA[ch]):
            _stroke(g, s)
        glyphs.append(g)

    # 预组合 25（浊音 / 半浊音）：基字放大 + 让位偏移 + 右上角落记号
    for ch, base, dx, dy, mark in VOICED_ORDER:
        note = f"平假名 {ch}（{base} + 浊音）"
        strokes = _scale_strokes(KANA[base])
        if ch in NARROW:
            # 底座横向收窄，把右上角让给浊音符（参照字体的做法）
            strokes, dx = _narrow_to_fit(strokes, DAKU if mark == "daku" else HAND)
            dy = 0
            note += "，基字横向收窄让位"
        g = Glyph(f"uni{CP[ch]:04X}", advance=1000, unicode=CP[ch], note=note)
        for s in _offset_strokes(strokes, dx, dy):
            _stroke(g, s)
        for s in (DAKU if mark == "daku" else HAND):
            _stroke(g, s)
        glyphs.append(g)

    # --- 新补 16 字 -------------------------------------------------------

    # 小假名：水平居中 + 贴基线（参照字体落位），直接按最终尺寸画
    for ch, cp in (("ぁ", 0x3041), ("ぃ", 0x3043), ("ぅ", 0x3045), ("ぇ", 0x3047),
                   ("ぉ", 0x3049), ("ゃ", 0x3083), ("ゅ", 0x3085), ("ょ", 0x3087),
                   ("ゎ", 0x308E), ("ゕ", 0x3095), ("ゖ", 0x3096)):
        g = Glyph(f"uni{cp:04X}", advance=1000, unicode=cp,
                  note=f"平假名 {ch}（小假名，新补）")
        strokes = SMALL[ch]
        if ch in SMALL_SCALE:
            # 尺寸修正（只动中心线坐标，权重与笔画拆法不动）
            strokes = _scale_only(strokes, SMALL_SCALE[ch])
        for s in _place_small(strokes):
            _stroke(g, s)
        glyphs.append(g)

    # っ：横向居中、纵向偏下（低位置的小写 つ）
    g = Glyph("uni3063", advance=1000, unicode=0x3063, note="平假名 っ（小假名 つ，新补）")
    for s in SMALL["っ"]:
        _stroke(g, s)
    glyphs.append(g)

    # ゔ U+3094：全尺寸 う + 浊点
    g = Glyph("uni3094", advance=1000, unicode=0x3094, note="平假名 ゔ（う + 浊点，新补）")
    for s in _scale_strokes(KANA["う"]):
        _stroke(g, s)
    for s in DAKU:
        _stroke(g, s)
    glyphs.append(g)

    # ゗ U+3097：ゝ + 斜杠
    g = Glyph("uni3097", advance=1000, unicode=0x3097, note="反复记号 ゗（ゝ + 斜杠，新补）")
    for s in ITER + SLASH:
        _stroke(g, s)
    glyphs.append(g)

    # ゘ U+3098：ゝ + 浊点
    g = Glyph("uni3098", advance=1000, unicode=0x3098, note="反复记号 ゘（ゝ + 浊点，新补）")
    for s in ITER:
        _stroke(g, s)
    for s in DAKU:
        _stroke(g, s)
    glyphs.append(g)

    # ゟ U+309F：ゝ + 半浊点
    g = Glyph("uni309F", advance=1000, unicode=0x309F, note="平假名 ゟ（ゝ + 半浊点，新补）")
    for s in ITER:
        _stroke(g, s)
    for s in HAND:
        _stroke(g, s)
    glyphs.append(g)

    # --- 记号（不参与放大，只挪落点）-------------------------------------

    # 浊音符 U+3099（零宽合记号）
    g = Glyph("uni3099", advance=0, unicode=0x3099, note="浊音符（零宽合记号，右上角两枚短斜画）")
    for s in DAKU:
        _stroke(g, s)
    glyphs.append(g)

    # 半浊音符 U+309A（零宽合记号）
    g = Glyph("uni309A", advance=0, unicode=0x309A, note="半浊音符（零宽合记号，右上角小圆环）")
    for s in HAND:
        _stroke(g, s)
    glyphs.append(g)

    # 浊点符号 U+309B / U+309C（独立形，advance 1000）
