def _band(pts, weight, miter_limit=2.5):
    """中心线折线 → 闭合轮廓：**外角硬折、内角开孔**（海报家族的轮廓语言）。

    对应 docs/03 GLY-002「外角以清晰硬折为主；弧形轮廓需光学平滑」：

    * 逐段沿法线左右各偏移 weight/2，得到左右两条偏移边；
    * **外角（凸转角）** 用两条偏移边的**交点**（miter）做硬折；
      miter 长度超过 ``miter_limit * (weight/2)`` 时改用**斜切（bevel）**，
      避免 48px 下出现尖刺毛刺（GLY-006）；
    * **内角（凹转角）** 两条偏移边会相交，直接**连两个偏移端点**（bevel），
      形成 V 形内凹 —— 即设计资料说的「内角必要时适度开孔」；
    * **端面保持平切**（垂直于中心线），与汉字横竖的端面一致；
    * **中心线坐标一个字都不改** —— 这里只改轮廓的处理方式（字形不动）。
    """
    h = weight / 2.0

    # 去掉重复点（零长段会让偏移线的方向算不出来）
    p = [pts[0]]
    for q in pts[1:]:
        if abs(q[0] - p[-1][0]) > 1e-9 or abs(q[1] - p[-1][1]) > 1e-9:
            p.append(q)
    if len(p) < 2:
        return []

    dirs = []
    for (x1, y1), (x2, y2) in zip(p, p[1:]):
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy)
        dirs.append((dx / length, dy / length))
    nseg = len(dirs)

    def side(sign):
        """sign=+1 取左侧偏移边，sign=-1 取右侧偏移边。"""
        nors = [(-uy * sign, ux * sign) for (ux, uy) in dirs]
        out = [(p[0][0] + nors[0][0] * h, p[0][1] + nors[0][1] * h)]
        for i in range(1, nseg):
            px, py = p[i]
            n1, n2 = nors[i - 1], nors[i]
            d1, d2 = dirs[i - 1], dirs[i]
            cross = d1[0] * d2[1] - d1[1] * d2[0]
            # 上一段偏移边的终点 / 下一段偏移边的起点
            e_pt = (px + n1[0] * h, py + n1[1] * h)
            s_pt = (px + n2[0] * h, py + n2[1] * h)
            if abs(cross) < 1e-12:
                # 共线：偏移线连续，直接接上
                out.append(s_pt)
                continue
            # 左转（cross>0）时左侧是内角；sign=-1 时左右对调
            inner = (cross * sign) > 0.0
            if inner:
                # 内角：斜切 → V 形内凹（开孔）
                out.append(e_pt)
                out.append(s_pt)
                continue
            # 外角：miter 硬折（超限则斜切）
            denom = 1.0 + d1[0] * d2[0] + d1[1] * d2[1]
            if denom < 1e-9:
                out.append(e_pt)
                out.append(s_pt)
                continue
            mx = (n1[0] + n2[0]) * h / denom
            my = (n1[1] + n2[1]) * h / denom
            if math.hypot(mx, my) > miter_limit * h:
                out.append(e_pt)
                out.append(s_pt)
            else:
                out.append((px + mx, py + my))
        out.append((p[-1][0] + nors[-1][0] * h, p[-1][1] + nors[-1][1] * h))
        return out

    left = side(1)
    right = side(-1)
    right.reverse()
    poly = left + right
    # 去掉相邻重复点（连续共线段会造出零长边）
    clean = []
    for pt in poly:
        if not clean or abs(pt[0] - clean[-1][0]) > 1e-9 or abs(pt[1] - clean[-1][1]) > 1e-9:
            clean.append(pt)
    if len(clean) > 1 and abs(clean[0][0] - clean[-1][0]) < 1e-9 and abs(clean[0][1] - clean[-1][1]) < 1e-9:
        clean.pop()
    return clean


def _circle(cx, cy, r, n=28):
    """正多边形近似的圆（点列，逆时针）。"""
    return [
        (cx + r * math.cos(2.0 * math.pi * i / n), cy + r * math.sin(2.0 * math.pi * i / n))
        for i in range(n)
    ]


def _stroke(g, s, dx=0.0, dy=0.0):
    """把一条笔画描述落到字形上。"""
    kind = s[0]
    if kind == "h":
        _, x1, x2, y, w = s
        g.hbar(x1 + dx, x2 + dx, y + dy, weight=w)
    elif kind == "v":
        _, x, y1, y2, w = s
        g.vbar(x + dx, y1 + dy, y2 + dy, weight=w)
    elif kind == "d":
        _, x1, y1, x2, y2, w = s
        g.diag(x1 + dx, y1 + dy, x2 + dx, y2 + dy, weight=w)
    elif kind == "p":
        _, pts, w = s
        g.poly([(x + dx, y + dy) for x, y in _band(pts, w)])
    elif kind == "dot":
        _, cx, cy, w, h, slant = s
        g.dot(cx + dx, cy + dy, w=w, h=h, slant=slant)
    elif kind == "ring":
        _, outer, inner = s
        g.ring(
            [(x + dx, y + dy) for x, y in outer],
            [(x + dx, y + dy) for x, y in inner],
        )
    else:
        raise ValueError(f"未知笔画类型：{kind!r}")


