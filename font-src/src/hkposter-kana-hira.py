def _band(pts, weight):
    """中心线折线 → 闭合轮廓：端面平切，转折处圆滑。

    每段按法线左右各偏移 weight/2，转角处补一段圆弧，
    左右两侧拼成一条简单闭合多边形（不自交）。
    """
    h = weight / 2.0
    segs = []
    for (x1, y1), (x2, y2) in zip(pts, pts[1:]):
        dx, dy = x2 - x1, y2 - y1
        length = math.hypot(dx, dy)
        if length < 1e-9:
            continue
        segs.append((x1, y1, x2, y2, dx / length, dy / length))
    if not segs:
        return []

    def side(sign):
        out = []
        for i, (x1, y1, x2, y2, ux, uy) in enumerate(segs):
            nx, ny = -uy * sign, ux * sign
            if i:
                _, _, _, _, pux, puy = segs[i - 1]
                pnx, pny = -puy * sign, pux * sign
                a0 = math.atan2(pny, pnx)
                a1 = math.atan2(ny, nx)
                delta = (a1 - a0 + math.pi) % (2 * math.pi) - math.pi
                steps = max(2, int(abs(delta) / math.radians(10)) + 1)
                for s in range(steps + 1):
                    a = a0 + delta * s / steps
                    out.append((x1 + math.cos(a) * h, y1 + math.sin(a) * h))
            else:
                out.append((x1 + nx * h, y1 + ny * h))
            out.append((x2 + nx * h, y2 + ny * h))
        return out

    left = side(1)
    right = side(-1)
    right.reverse()
    return left + right


def _circle(cx, cy, r, n=28):
    """正多边形近似的圆（点列，逆时针）。"""
    return [
        (cx + r * math.cos(2.0 * math.pi * i / n), cy + r * math.sin(2.0 * math.pi * i / n))
        for i in range(n)
    ]


def _stroke(g, s, dx=0.0, dy=0.0):
    """把一条笔画描述落到字形上。"""
    kind = s[0]
    if kind == "h":
        _, x1, x2, y, w = s
        g.hbar(x1 + dx, x2 + dx, y + dy, weight=w)
    elif kind == "v":
        _, x, y1, y2, w = s
        g.vbar(x + dx, y1 + dy, y2 + dy, weight=w)
    elif kind == "d":
        _, x1, y1, x2, y2, w = s
        g.diag(x1 + dx, y1 + dy, x2 + dx, y2 + dy, weight=w)
    elif kind == "p":
        _, pts, w = s
        g.poly([(x + dx, y + dy) for x, y in _band(pts, w)])
    elif kind == "dot":
        _, cx, cy, w, h, slant = s
        g.dot(cx + dx, cy + dy, w=w, h=h, slant=slant)
    elif kind == "ring":
        _, outer, inner = s
        g.ring(
            [(x + dx, y + dy) for x, y in outer],
            [(x + dx, y + dy) for x, y in inner],
        )
    else:
        raise ValueError(f"未知笔画类型：{kind!r}")


