    g.vbar(195, 150, 740, W_MAIN)                   # 竖
    g.poly([(147, 230), (243, 230), (243, 100),      # 竖钩（向左下挑）
            (104, 110)])
    g.diag(95, 300, 215, 390, W_SEC)                # 提（自左下升向右）


