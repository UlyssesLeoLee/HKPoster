    g.hbar(60, 940, 48, W_MAIN)                     # 下横（贯通）
    g.vbar(150, 48, 750, W_THIN)                    # 竖①（最左）
    g.vbar(360, 48, 750, W_THIN)                    # 竖②
    g.vbar(600, 48, 750, W_THIN)                    # 竖③
    g.vbar(830, 48, 750, W_THIN)                    # 竖④（最右）
    g.hbar(150, 830, 400, W_THIN)                   # 中横（在四竖之间贯通）


