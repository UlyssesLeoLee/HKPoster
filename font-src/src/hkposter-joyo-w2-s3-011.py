"""HK Poster Heavy —— Jōyō 常用漢字 joyo-w2-s3-011。

本批 24 字，笔画范围 10–13，取自 2010 年文化厅《常用漢字表》。

【整体设计取舍】
- 字面框 x 60..940 / y 0..820，与繁体汉字完全一致；advance = 1000。
- 笔画权重：主 96 / 次 92 / 细 84 / 点 84–96。本批笔画 10–13，偏密，
  故「横画密排区」（喜/豊/軽/善/幸 等竖向堆 4 条以上横画者）统一降到 84，
  只在单字的最外两条横画回到 92/96，保证批内「有的太轻、有的太闷」不出现。
- 竖画主档 92，极窄的部件（氵、糸、扌）用 84 细档，避免左偏旁糊成黑块。
- 内白硬规矩：所有口/日/目/田/月/貝 型方框的腔高 ≥ 24 单位；
  竖与竖的净间隙 ≥ 60 单位（狭长部件如 氵/糸 的斜画按实际墨迹放宽到 48）。
- 端点：横竖撇捺全部平切硬边；点与短撇用斜切平行四边形，
  斜切档位只用契约允许的 26 / 22 / 20 / 18 / 16 / 14 / 0 / −14。
- 骨架来自参照字体（M PLUS 1p Black）的比例与部件分区，
  只改笔画设计与重量，不改笔画走向（项目所有者 2026-10-25）。

【批内同族观感】
- 同一部件在全批复用同一套坐标与笔画拆法：
  氵（測/浮）、糸（絶/絡）、扌（損）、貝（測/損）、各（略/絡）、口/日/月/目/田 方框。
- 同类记号全批同档：氵上点 = 26（短撇），氵中点 = −14（右下的点），
  辶的点 = −14，寸的点 = −14，厶的点 = −14，丷左 = −14，丷右 = +14，
  亠的点（方）= 0（竖点）。
"""

