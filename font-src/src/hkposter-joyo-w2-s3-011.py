# ---------------------------------------------------------------------------
# 对齐辅助：横画按「墨迹上缘」定位（内白永远从上一笔的下缘量起，避免目测误差）
# ---------------------------------------------------------------------------
def bar(g, x1, x2, y_top, w=W_MAIN):
    """横画：墨迹上缘对齐 y_top，下缘 = y_top - w。"""
    g.hbar(x1, x2, y_top - w / 2.0, weight=w)


def vhook(g, x, y_bot, w=W_THIN, dx=50, dy=50):
    """竖笔底端向左上挑出的钩（亅 / 竖钩）。"""
    g.diag(x, y_bot, x - dx, y_bot + dy, weight=w)


def wogou(g, x_left, y_top, x_right, y_bot, w=W_MAIN, hook=52):
    """卧钩（心底 / 辶底）：斜下 + 横 + 右上挑。"""
    g.diag(x_left, y_top, x_left + 96, y_bot, weight=w)
    g.hbar(x_left + 96, x_right, y_bot + w / 2.0, weight=w)
    g.diag(x_right, y_bot, x_right + hook, y_bot + hook, weight=W_THIN)


# ---------------------------------------------------------------------------
# 复用部件（同族坐标）
# ---------------------------------------------------------------------------
def sanzui(g, cx=150, top=760):
    """氵：三笔（短撇点 26 / 右下点 −14 / 提）。

    氵是全批最细的偏旁，但笔画少（3 画），故整体给到 104 粗档，
    否则与「浮」这类 10 画轻字放在一起会显得过轻（check_glyphs 墨量率下限）。
    """
    g.dot(cx=cx, cy=top - 48, w=108, h=148, slant=26)
    g.dot(cx=cx - 12, cy=top - 240, w=108, h=142, slant=-14)
    g.diag(cx - 45, 85, cx + 98, 248, weight=104)


def maw_silk(g, x0, y0):
    """糸（左偏旁）：幺（撇折 x2 + 点）+ 小（丨 + 撇 + 点）。"""
    # 幺
    g.diag(x0 + 185, y0, x0 + 80, y0 - 150, weight=W_THIN)
    bar(g, x0 + 80, x0 + 230, y0 - 150, W_THIN)
    g.diag(x0 + 245, y0 - 110, x0 + 115, y0 - 280, weight=W_THIN)
    bar(g, x0 + 115, x0 + 265, y0 - 280, W_THIN)
    g.dot(cx=x0 + 270, cy=y0 - 260, w=W_THIN, h=84, slant=-14)
    # 小
    g.vbar(x0 + 170, y0 - 320, 0, W_SEC)
    g.diag(x0 + 100, y0 - 350, x0 + 30, y0 - 690, weight=W_THIN)
    g.dot(cx=x0 + 250, cy=y0 - 380, w=W_THIN, h=84, slant=-14)


def kakushi(g, x0, x1, y_top, y_bot, w=W_SEC):
    """口型方框（左竖 / 顶横 / 右竖 / 底横），内白由上下缘决定。"""
    g.vbar(x0 + w / 2.0, y_top, y_bot, w)
    g.vbar(x1 - w / 2.0, y_top, y_bot, w)
    bar(g, x0, x1, y_top, w)
    bar(g, x0, x1, y_bot + w, w)


