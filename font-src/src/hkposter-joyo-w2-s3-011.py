# 1. 測 U+6E2C —— 氵 + 貝 + 刂（12 画）
# ===========================================================================
def glyph_ce():
    """測：水偏旁 + 貝（目 + 八）+ 刂（短竖 + 长竖带钩）。

    部件分区：氵 x 60..245 / 貝 x 290..690 / 刂 x 755..905。
    貝 的目部三横：顶 772、中 668、底 442；腔高 54 / 136，远高于 24。
    """
    g = Glyph("uni6E2C", advance=1000, unicode=0x6E2C, note="測：水偏旁+貝+刂")
    sanzui(g, cx=150, top=760)
    # 貝
    bar(g, 290, 690, 820, W_MAIN)          # 目顶横
    g.vbar(338, 820, 350, W_MAIN)           # 目左竖
    g.vbar(642, 820, 350, W_MAIN)           # 目右竖
    bar(g, 338, 642, 670, W_SEC)            # 眼中横  (腔 724-670 = 54)
    bar(g, 338, 642, 442, W_SEC)            # 目底横  (腔 578-442 = 136)
    g.diag(452, 330, 322, 20, weight=W_SEC)  # 八的撇
    g.diag(548, 330, 694, 20, weight=W_SEC)  # 八的捺
    # 刂
    g.vbar(792, 570, 330, W_SEC)            # 短竖
    g.vbar(880, 820, 100, W_MAIN)           # 长竖
    vhook(g, 880, 100)
    return g


