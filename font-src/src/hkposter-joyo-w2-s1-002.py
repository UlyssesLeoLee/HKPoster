"""HK Poster Heavy —— Jōyō 常用漢字 joyo-w2-s1-002。

本批 40 字，笔画范围 1–5，取自 2010 年文化厅《常用漢字表》。

整体设计取舍
------------
* 字面框：x 60..940、y 0..820，与 zh-HK 繁体汉字完全一致，中英日混排时基线与字高不跳动。
* 笔画权重四档：主 96 / 次 92 / 细 84 / 点 84–88。
  1–2 画的字（乙、又、刀）全用主档 96，否则同批里会「太轻」；
  3–4 画的主干用 96、附属构件用 92；
  5 画且内部拥挤的字（皿、丼、迅、尻、瓦、尾字族）在内白处局部降到 84。
* 同一部件复用：氵（汁）、尸（尻、尼、尺）、九（尻）、又（又、奴）、口（召）、
  子（孔）、丂（巧）、乚/弯钩（凡、冗、尻、尼、孔）、亅（才、寸、矛）在本批内
  采用同一套坐标与笔画拆法，只做位置与大小的光学校正（docs/03 GLY-004）。
* 对齐语义：横画按「墨迹上缘贴 820 / 下缘贴 0」反推中心线（bar_top / bar_base）；
  斜画按「墨迹外接框」反推中心线端点（_d），确保笔画不越出字面框。
* 内白下限：密排横画之间 >= 24，竖与竖之间 >= 60（GLY-006）。
* 不做逐字机械挤压或倾斜（docs/02 偏差 D）；只调部件位置与大小。
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

FONT_SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FONT_SRC / "scripts"))

from hkbuild import Glyph, write_ufo  # noqa: E402

W_MAIN = 96
W_SEC = 92
W_THIN = 84
W_DOT = 84

# 字面框（与 zh-HK 繁体汉字一致）
X_MIN = 60.0
X_MAX = 940.0
Y_BASE = 0.0
Y_TOP = 820.0


def bar_top(w: float = W_SEC) -> float:
    """横画中心线：墨迹上缘对齐字面框顶 820。"""
    return Y_TOP - w / 2.0


def bar_base(w: float = W_MAIN) -> float:
    """横画中心线：墨迹下缘对齐基线 0。"""
    return Y_BASE + w / 2.0


def _dline(x1: float, y1: float, x2: float, y2: float, w: float):
    """斜笔画中心线端点：由目标墨迹外接框 (x1,y1)-(x2,y2) 反算。

    笔画为「中心线 + 垂直厚度」，端部按垂直中心线切平，
    故墨迹在 x 方向外伸 (w/2)*|uy|、在 y 方向外伸 (w/2)*|ux|。
    """
    dx, dy = x2 - x1, y2 - y1
    length = math.hypot(dx, dy)
    if length == 0:
        return x1, y1, x2, y2
    ux, uy = dx / length, dy / length
    hw = w / 2.0
    ax, ay = abs(ux), abs(uy)
    sx = 1.0 if dx >= 0 else -1.0
    sy = 1.0 if dy >= 0 else -1.0
    return (
        x1 + sx * hw * ay,
        y1 + sy * hw * ax,
        x2 - sx * hw * ay,
        y2 - sy * hw * ax,
    )


def _d(g: Glyph, x1: float, y1: float, x2: float, y2: float, w: float = W_MAIN) -> None:
    """按目标墨迹外接框落一条斜笔画。"""
    cx1, cy1, cx2, cy2 = _dline(x1, y1, x2, y2, w)
    g.diag(cx1, cy1, cx2, cy2, weight=w)


