# 屈 U+5C48
# ---------------------------------------------------------------------------
def glyph_kutsu() -> Glyph:
    """屈。

    包围结构：尸(80..880, 554..810) + 出(290..745, 78..530)。
    尸：横折（120..880 / 竖 870）+ 横 120..870 + 撇自 (180,600) 落到基线。
    出 = 5 画：上竖折（左竖 330 + 中横 330..710）+ 中竖 520 + 上右竖 705
      + 下竖折（左竖 290 + 底横 290..750）+ 下右竖 745。
    """
    g = Glyph("uni5C48", advance=1000, unicode=0x5C48, note="屈（Jōyō joyo-w2-s2-015）")

    # ---- 尸 ----
    g.hbar(120, 880, 760, weight=W_SEC)          # 尸的横
    g.vbar(870, 760, 600, weight=W_SEC)          # 尸的竖
    g.hbar(120, 870, 600, weight=W_SEC)          # 尸的横
    g.diag(180, 600, 105, 12, weight=W_SEC)      # 尸的撇（墨迹下缘落在基线）

    # ---- 出 ----
    g.vbar(330, 460, 390, weight=W_THIN)         # 出上竖折的竖
    g.hbar(330, 710, 390, weight=W_THIN)         # 出上竖折的横
    g.vbar(520, 530, 90, weight=W_THIN)          # 出的中竖
    g.vbar(705, 460, 390, weight=W_THIN)         # 出的上右竖
    g.vbar(290, 280, 120, weight=W_THIN)         # 出下竖折的竖
    g.hbar(290, 750, 120, weight=W_THIN)         # 出下竖折的横
    g.vbar(745, 280, 120, weight=W_THIN)         # 出的下右竖
    return g


