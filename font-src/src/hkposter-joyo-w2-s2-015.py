# 怖 U+6016 —— 忄 + 布
# ---------------------------------------------------------------------------
def glyph_bi() -> Glyph:
    """怖。

    左右结构：忄(x 60..335) + 布(x 380..940)。
    忄：竖 x=200（墨迹 152..248）贯通上下；左点 x 63..145、右点 255..335，
      两点与竖之间各留 7 单位白口，不与竖粘连。
    布：横 y 682..778；撇自 (620,800) 斜下至 (400,560)，横跨一的上部；
      巾的上横 584..676，左竖 459..551、中竖 647..743、右竖 844..936，
      竖距 96 单位，内白充足（GLY-006）。
    """
    g = Glyph("uni6016", advance=1000, unicode=0x6016, note="怖（Jōyō joyo-w2-s2-015）")

    # ---- 忄 ----
    g.vbar(200, 770, 40, weight=W_MAIN)          # 忄的竖
    g.dot(105, 585, w=82, h=120, slant=-14)      # 忄的左点（左下倾）
    g.dot(295, 600, w=82, h=120, slant=14)       # 忄的右点（右下倾）

    # ---- 布 ----
    g.hbar(380, 940, 730, weight=W_MAIN)         # 布的横
    g.diag(620, 782, 400, 550, weight=W_MAIN)    # 布的撇
    g.hbar(500, 900, 630, weight=W_SEC)          # 巾的上横
    g.vbar(505, 630, 230, weight=W_SEC)          # 巾的左竖
    g.vbar(890, 630, 230, weight=W_SEC)          # 巾的右竖
    g.diag(890, 230, 820, 170, weight=W_THIN)    # 巾的钩
    g.vbar(695, 630, 40, weight=W_MAIN)          # 巾的中竖
    return g


