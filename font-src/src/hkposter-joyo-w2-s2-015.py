# 径 U+5F84
# ---------------------------------------------------------------------------
def glyph_kei() -> Glyph:
    """径。

    左右结构：彳(x 60..330) + 圣(x 400..940)。
    圣 = 又（横 450..880 + 撇 870→500 + 捺 560→880）+ 土（横 450..900 + 竖 675 + 底横 400..940）。
    又的两腿在 (620,500) 附近交叉，土的竖落到底横上，互不粘连。
    """
    g = Glyph("uni5F84", advance=1000, unicode=0x5F84, note="径（Jōyō joyo-w2-s2-015）")

    # ---- 彳 ----
    draw_step(g)

    # ---- 圣 ----
    g.hbar(450, 880, 640, weight=W_SEC)          # 又的横
    g.diag(870, 640, 500, 380, weight=W_SEC)     # 又的撇
    g.diag(560, 630, 880, 380, weight=W_SEC)     # 又的捺
    g.hbar(450, 900, 250, weight=W_SEC)          # 土的横
    g.vbar(675, 250, 120, weight=W_SEC)          # 土的竖
    g.hbar(400, 940, 80, weight=W_SEC)           # 土的底横
    return g


