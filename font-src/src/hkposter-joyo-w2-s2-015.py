# 栃 U+6803
# ---------------------------------------------------------------------------
def glyph_tochi() -> Glyph:
    """栃。

    左右结构：木(x 60..360) + 万(x 430..940)。
    木字旁与「枝」同款（GLY-004）。
    万 = 顶横 430..940（694..786）+ 长撇（600,740）→(470,60）+ 横折钩
      （横 590..900 / 竖 890 带钩）。
    9 画密字：万部的横叠（顶横与中横）间距仅 88 单位，故中横降到 84。
    """
    g = Glyph("uni6803", advance=1000, unicode=0x6803, note="栃（Jōyō joyo-w2-s2-015）")

    # ---- 木 ----
    draw_tree(g)

    # ---- 万 ----
    g.hbar(430, 940, 740, weight=W_MAIN)         # 万的顶横
    g.diag(600, 740, 465, 8, weight=W_SEC)       # 万的撇（墨迹下缘落在基线）
    g.hbar(590, 900, 580, weight=W_THIN)         # 万的横折钩的横
    g.vbar(890, 580, 220, weight=W_SEC)          # 万的竖
    g.diag(890, 220, 820, 160, weight=W_THIN)    # 万的钩
    return g


