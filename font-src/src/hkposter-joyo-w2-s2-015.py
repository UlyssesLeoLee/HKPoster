"""HK Poster Heavy —— Jōyō 常用漢字 joyo-w2-s2-015。

本批 32 字，笔画范围 6–9，取自 2010 年文化厅《常用漢字表》。

坐标约定（与 cjk-core / cjk-dense 两个 base master 一致）：
    UPM 1000，y 向上，基线 y=0，advance=1000；
    字面框 x 60..940、y 0..820；CJK 顶线 820。

整体设计取舍
------------
1. **同族观感优先于逐字发挥**：本批 6–9 画，密度接近，左偏旁一律复用同一套
   坐标与笔画拆法（GLY-004）——
     扌 x 60..320 / 氵 x 60..310 / 彳 x 60..330 / 犭 x 60..320 /
     月 x 60..380 / 木 x 60..360 / 氵的提、扌的提全批同角度。
   右部件统一落在 x 380..940 区间，字面左右两端的留白对所有字一致。
2. **权重分层**：主笔画 96、次笔画 92、细笔画 84；6 画的疏字（耳 / 虫 / 叫）
   主笔画全部上到 96，9 画的密字（珍 / 狭 / 胞 / 浄 / 肺 / 貞 / 栃）
   在密排处局部减到 84（GLY-001），避免批内"有的太轻、有的太闷"。
3. **海报端点**：横竖撇捺一律平切硬边（hkbuild 的 hbar / vbar / diag），
   点与短撇一律斜切平行四边形（g.dot）。
4. **记号倾角只用既有档位**：26 / 22 / 20 / 18 / 16 / 14 / −14 / 0。
   与 base master 实测一致的语义（见 font-src/masters/hkposter-cjk-core.ufo
   与 hkposter-cjk-dense.ufo 的既有字形）：
     slant < 0  → 点向左下倾（左点、丷左、爫的点、心的左点）
     slant > 0  → 点向右下倾（右点、丷右、虫的点、城的点）
     slant = 0  → 竖点（亠的点、主的点）
     26         → 氵的两点（与 cjk-core 的「港」同档）
     14 / −14   → 丷、小、心的成对点
5. **角度不改**：所有斜笔画的走向照标准骨架（参照 E:/hkposter-refs/ 的
   M PLUS 1p Black 与 Zen Kaku Gothic New Black 的比例与骨架，
   两者均为 SIL OFL 1.1），只改笔画设计与端点处理。
6. **内白**：密排处横画间距 ≥ 24 单位，竖与竖之间 ≥ 60 单位（GLY-006）。
"""

from __future__ import annotations

import sys
from pathlib import Path

FONT_SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FONT_SRC / "scripts"))

from hkbuild import Glyph, write_ufo  # noqa: E402

W_MAIN = 96
W_SEC = 92
W_THIN = 84
W_DOT = 84

CJK_TOP = 820


# ---------------------------------------------------------------------------
# 对齐约定
# ---------------------------------------------------------------------------
# 横：墨迹占 y±weight/2，中心线写「墨迹中心」的 y；
# 竖：墨迹两端即中心线端点；
# 斜：墨迹厚度垂直于中心线，墨迹下缘比中心线低 (weight/2)·|dx|/len——
#     下文所有需要「撇捺落到基线」的斜笔画，端点已按此换算，
#     故墨迹下缘正好落在 y=0（例：栃的万的撇端点 (465,8)，
#     off = 46×135/744 ≈ 8.3，墨迹下缘 = 8 − 8.3 ≈ 0）。


# ---------------------------------------------------------------------------
# 左偏旁（全批复用的同一套坐标与笔画拆法）
# ---------------------------------------------------------------------------
def draw_hand(g: Glyph) -> None:
    """扌（x 60..320）：横 + 竖 + 提。"""
    g.hbar(70, 310, 545, weight=W_SEC)          # 横
    g.vbar(195, 760, 60, weight=W_SEC)           # 竖
    g.diag(80, 300, 305, 395, weight=W_SEC)      # 提（固定 22.9°）


def draw_water(g: Glyph) -> None:
    """氵（x 60..310）：上点 + 下点 + 提。"""
    g.dot(155, 690, w=104, h=140, slant=26)      # 上点（26 档，与「港」同）
    g.dot(145, 470, w=104, h=140, slant=26)      # 下点
    g.diag(75, 150, 285, 305, weight=W_SEC)      # 提


def draw_step(g: Glyph) -> None:
    """彳（x 60..330）：上撇 + 下撇 + 竖。"""
    g.diag(300, 782, 130, 640, weight=W_MAIN)    # 第一撇
    g.diag(310, 660, 95, 400, weight=W_MAIN)     # 第二撇
    g.vbar(185, 450, 40, weight=W_MAIN)          # 竖


def draw_dog(g: Glyph) -> None:
    """犭（x 60..320）：撇 + 弯钩 + 撇。"""
    g.diag(320, 780, 120, 600, weight=W_MAIN)    # 首撇
    g.vbar(205, 790, 130, weight=W_MAIN)         # 弯钩的竖
    g.diag(205, 130, 140, 190, weight=W_THIN)    # 弯钩的钩
    g.diag(300, 540, 85, 330, weight=W_MAIN)     # 交叉的撇


def draw_flesh(g: Glyph) -> None:
    """月（x 60..380）：撇 + 横折钩 + 两横。"""
    g.diag(250, 790, 175, 60, weight=W_SEC)      # 撇（微左倾 6°）
    g.hbar(235, 330, 755, weight=W_THIN)         # 横折钩的横
    g.vbar(330, 755, 110, weight=W_SEC)          # 横折钩的竖
    g.diag(330, 110, 265, 165, weight=W_THIN)    # 钩
    g.hbar(224, 330, 540, weight=W_THIN)         # 内横 1
    g.hbar(203, 330, 330, weight=W_THIN)         # 内横 2


def draw_tree(g: Glyph) -> None:
    """木（x 60..360）：横 + 竖 + 撇 + 点（捺变点，木字旁惯例）。"""
    g.hbar(70, 350, 620, weight=W_SEC)           # 横
    g.vbar(210, 790, 40, weight=W_SEC)           # 竖
    g.diag(215, 620, 80, 300, weight=W_SEC)      # 撇
    g.dot(300, 560, w=W_DOT, h=110, slant=14)      # 捺变点（右下，14 档）


def draw_horse(g: Glyph) -> None:
    """牜（x 60..330）：撇 + 上横 + 下横 + 竖。"""
    g.diag(260, 772, 140, 675, weight=W_MAIN)    # 首撇
    g.hbar(110, 300, 640, weight=W_MAIN)         # 上横
    g.hbar(70, 330, 470, weight=W_MAIN)          # 下横（长）
    g.vbar(210, 790, 60, weight=W_MAIN)          # 竖


def draw_mountain(g: Glyph) -> None:
    """山（x 60..330）：中竖 + 左右竖 + 底横。"""
    g.vbar(195, 790, 120, weight=W_SEC)          # 中竖（最高）
    g.vbar(85, 620, 90, weight=W_SEC)            # 左竖
    g.vbar(305, 620, 90, weight=W_SEC)           # 右竖
    g.hbar(85, 305, 90, weight=W_SEC)            # 底横


def draw_female(g: Glyph) -> None:
    """女（x 60..430）：撇点 + 撇 + 横。"""
    g.diag(300, 790, 150, 480, weight=W_MAIN)    # 撇点的撇段
    g.diag(150, 480, 330, 330, weight=W_MAIN)    # 撇点的捺段
    g.diag(330, 700, 110, 200, weight=W_MAIN)    # 撇
    g.hbar(60, 430, 380, weight=W_MAIN)          # 横


def draw_zhi(g: Glyph, x0=380) -> None:
    """支（x0..940）：横 + 竖 + 横撇 + 捺。"""
    g.hbar(x0 + 60, 940, 700, weight=W_SEC)              # 十的横
    g.vbar(x0 + 310, 780, 520, weight=W_SEC)             # 十的竖
    g.hbar(x0 + 80, 900, 480, weight=W_SEC)              # 又的横
    g.diag(900, 480, 520, 60, weight=W_SEC)              # 又的撇
    g.diag(x0 + 140, 470, 920, 60, weight=W_MAIN)        # 又的捺


