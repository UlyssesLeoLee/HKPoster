def glyph_kyou2() -> Glyph:
    """叫。

    左右结构：口(x 80..380) + 丩(x 480..900)。
    口为窄高框（墨迹 60..640），是叫与「呂」等同框字的区别。
    丩 = 短竖 520（60..470）+ 底横 520..800 + 长竖 790（60..790）。
    6 画疏字，主笔画全部 96。
    """
    g = Glyph("uni53EB", advance=1000, unicode=0x53EB, note="叫（Jōyō joyo-w2-s2-015）")

    # ---- 口 ----
    g.hbar(80, 380, 640, weight=W_SEC)           # 口的上横
    g.vbar(85, 640, 60, weight=W_SEC)            # 口的左竖
    g.vbar(375, 640, 60, weight=W_SEC)           # 口的右竖
    g.hbar(85, 375, 60, weight=W_SEC)            # 口的下横

    # ---- 丩 ----
    g.vbar(520, 470, 60, weight=W_SEC)           # 短竖
    g.hbar(520, 800, 60, weight=W_SEC)           # 底横
    g.vbar(790, 790, 60, weight=W_SEC)           # 长竖
    return g


