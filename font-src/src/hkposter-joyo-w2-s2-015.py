# 岐 U+5C90
# ---------------------------------------------------------------------------
def glyph_aki() -> Glyph:
    """岐。

    左右结构：山(x 60..330) + 支(x 380..940)。
    山为偏旁形：中竖 195 最高，左右竖 85 / 305，底横 y 44..136。
    支与「枝」同款（GLY-004）。
    """
    g = Glyph("uni5C90", advance=1000, unicode=0x5C90, note="岐（Jōyō joyo-w2-s2-015）")

    # ---- 山 ----
    draw_mountain(g)

    # ---- 支 ----
    draw_zhi(g)
    return g


