def _h(g: Glyph, x1: float, x2: float, y: float, w: float = W_MAIN) -> None:
    """水平笔画：y 为墨迹中心线，墨迹占 y ± w/2。"""
    g.hbar(x1, x2, y, weight=w)


def _v(g: Glyph, x: float, y1: float, y2: float, w: float = W_MAIN) -> None:
    """垂直笔画：y1..y2 即墨迹上下端点。"""
    g.vbar(x, y1, y2, weight=w)


def _d(g: Glyph, x1: float, y1: float, x2: float, y2: float, w: float = W_MAIN) -> None:
    """斜笔画：中心线两端点，厚度垂直于中心线。"""
    g.diag(x1, y1, x2, y2, weight=w)


def _p(g: Glyph, cx: float, cy: float, w: float = W_DOT, hh: float = 84,
       slant: float = 0) -> None:
    """点/短撇：平行四边形，中心 (cx, cy)。"""
    g.dot(cx, cy, w=w, h=hh, slant=slant)


def _men(g: Glyph) -> None:
    """門 字框（間 / 開 / 問 共用）。

    分区：左竖 x=108（通高 0..820）；左侧日框 x 108..344（顶横 c=774、
    内横 c=650 / 528、折竖 x=302）；右侧日框 x 596..892（顶横 c=774、
    内横 c=650、折竖 x=638）；右竖 x=892（通高）。
    """
    _v(g, 108, 820, 0, W_SEC)
    _h(g, 108, 344, 774, W_SEC)
    _h(g, 108, 344, 650, W_THIN)
    _h(g, 108, 344, 528, W_THIN)
    _v(g, 302, 820, 528, W_THIN)
    _h(g, 596, 892, 774, W_SEC)
    _h(g, 596, 892, 650, W_THIN)
    _v(g, 638, 820, 650, W_THIN)
    _v(g, 892, 820, 0, W_SEC)


def _ear(g: Glyph, sx: float, rx: float) -> None:
    """⻏ 邑部右耳（部 / 都 共用）。

    竖 x=sx 通高 0..820；上横墨迹上缘贴 820（sx..rx，c=774）；
    上凸右竖 x=rx（774..540）；双凸折线 540→450→330→240 折点贴竖。
    """
    _v(g, sx, 820, 0, W_MAIN)
    _h(g, sx, rx, 774, W_SEC)
    _v(g, rx, 774, 540, W_THIN)
    _d(g, rx, 540, sx + 18, 450, W_THIN)
    _d(g, sx + 18, 450, rx - 40, 330, W_THIN)
    _d(g, rx - 40, 330, sx + 18, 240, W_THIN)


def _si(g: Glyph) -> None:
    """糸 偏（経 / 統 共用）：x 60..412。

    撇1 diag(230,790→160,700)；撇折1 diag(210,700→130,570)+横 c=590；
    撇折2 diag(280,640→160,470)+横 c=470；竖钩 x=240（470..0）；
    左右点 x=120 / 356。
    """
    _d(g, 230, 790, 160, 700, W_THIN)
    _d(g, 210, 700, 130, 570, W_SEC)
    _h(g, 130, 290, 590, W_SEC)
    _d(g, 280, 640, 160, 470, W_SEC)
    _h(g, 160, 320, 470, W_SEC)
    _v(g, 240, 470, 0, W_SEC)
    _p(g, 120, 330, W_DOT, 84)
    _p(g, 356, 330, W_DOT, 84)


