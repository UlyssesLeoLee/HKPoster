"""HK Poster Heavy —— Jōyō 常用漢字 joyo-w2-s3-001。

本批 24 字，笔画范围 10–13，取自 2010 年文化厅《常用漢字表》。

整体设计取舍
------------
1. 字面框：x 60..940、y 0..820，advance = 1000（与 zh-HK 繁体汉字同框，
   便于中英日混排；基线 y=0，顶线 y=820）。
2. 笔画权重：主 96 / 次 92 / 细 84 / 点 84（与 zh-HK 繁体同一档）。
   笔画少的字（時/高/部/党/員/都）以 96 为主；笔画多的字（業/新/戦/意/統）
   在密排处局部减重到 84，避免同批内「有的太轻、有的太闷」（GLY-001）。
3. 水平层位：本批统一使用 774 / 688 / 560 / 508 / 420 / 356 / 300 / 242 /
   192 / 128 / 48 这类中心线，横画叠横画的净空 ≥ 24 单位；
   竖与竖的净空 ≥ 60 单位（GLY-006）。
4. 部件复用（docs/03 GLY-004）：門 / ⻏（邑部右耳）/ 糸 / 力 / 日 / 目 / 田 /
   口 / 儿 等在本批内共用同一套坐标与笔画拆法，只随所处位置做等比光学校正。
5. 字体本体与海报特效分离：本文件只写轮廓，不含霓虹/描边/金属/旧化。
"""

from __future__ import annotations

