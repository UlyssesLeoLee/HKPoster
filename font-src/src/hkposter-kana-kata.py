def _circle(cx: float, cy: float, r: float, n: int = 32) -> list[tuple[int, int]]:
    """整点圆周点列（契约要求坐标取整）。"""
    return [
        (
            int(round(cx + r * math.cos(2.0 * math.pi * i / n))),
            int(round(cy + r * math.sin(2.0 * math.pi * i / n))),
        )
        for i in range(n)
    ]


