from hkbuild import Glyph, write_ufo  # noqa: E402

# ---- 权重档 -------------------------------------------------------------
W_MAIN = 96   # 主
W_SEC = 92    # 次
W_THIN = 84   # 细
W_DOT = 84    # 点

# ---- 批内共用坐标原语 ---------------------------------------------------
BOX_L = 140.0      # 外框类左竖中心线
BOX_R = 860.0      # 外框类右竖中心线
BOX_L_N = 175.0    # 竖画较多、字面收窄的左竖（日/田/目/月/円/用/四）
BOX_R_N = 825.0    # 竖画较多、字面收窄的右竖
AXIS = 500.0       # 中轴
FACE_L = 60.0      # 字面框左界
FACE_R = 940.0     # 字面框右界
TOP = 820.0        # 字面框上界
BASE = 0.0         # 字面框下界


# ---- 对齐辅助（照 bar_top / bar_base / diag_cap_base 的做法自写） -------
def vbar(g: Glyph, x: float, y1: float, y2: float, w: float = W_MAIN) -> None:
    """竖画：中心线 x，y1/y2 即墨迹上下端点。"""
    g.vbar(x, y1, y2, weight=w)


def hbar_top(g: Glyph, x1: float, x2: float, y: float = TOP, w: float = W_MAIN) -> None:
    """横画：墨迹**上缘**对齐 y（中心线内缩半个笔画宽）。"""
    g.hbar(x1, x2, y - w / 2.0, weight=w)


def hbar_base(g: Glyph, x1: float, x2: float, y: float = BASE, w: float = W_MAIN) -> None:
    """横画：墨迹**下缘**对齐 y（中心线内缩半个笔画宽）。"""
    g.hbar(x1, x2, y + w / 2.0, weight=w)


def hbar_mid(g: Glyph, x1: float, x2: float, y: float, w: float = W_MAIN) -> None:
    """横画：中心线在 y（墨迹占 y ± w/2）。"""
    g.hbar(x1, x2, y, weight=w)


def dbar(g: Glyph, x1: float, y1: float, x2: float, y2: float, w: float = W_MAIN) -> None:
    """斜画：中心线两端点，厚度垂直于中心线；收笔平切会多出半个笔宽的余量。"""
    g.diag(x1, y1, x2, y2, weight=w)


def hook_left(g: Glyph, x: float, y: float, dx: float = -60.0, dy: float = 60.0,
              w: float = W_THIN) -> None:
    """横折钩 / 竖钩的钩：自 (x, y) 向左上挑出（批内统一钩向）。"""
    g.diag(x, y, x + dx, y + dy, weight=w)


