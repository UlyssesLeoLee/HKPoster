"""HK Poster Heavy —— Jōyō 常用漢字 joyo-s1-001。

本批 40 字，笔画范围 1–5，取自 2010 年文化厅《常用漢字表》。

整体设计取舍
------------
* **字面框**：x 60..940，y 0..820，advance 1000。跟 zh-HK 繁体批次完全一致，
  中 / 日 / 英混排时基线与字面大小齐平（AGENTS.md §CJK 分档）。
* **权重**：漢字四档 —— 主 96 / 次 92 / 细 84 / 点 84–96，与繁体同档。
  - 笔画少的字（一 二 三 十 人 入 八 九 力）统一用主档 96，避免"有的太轻"；
  - 笔画多的字（本 生 民 目 出 主 用 田 四 外 代 立 市 民 氏）在拥挤处局部降到 84–92，
    保证内白（横叠横 ≥ 24、竖叠竖 ≥ 60，GLY-006）不被吃掉。
* **同族观感（批内复用，docs/03 GLY-004）**：
  - 外框类（日 田 目 月 円 用 四 内）的左右竖共用 BOX_L / BOX_R / BOX_L_N / BOX_R_N，
    顶横一律 `hbar_top(y=820)`、底横一律 `hbar_base(y=0)`、中横一律 `hbar_mid()`；
  - 「亻」部件（代 化）复用同一套 x 坐标与拆法；
  - 「八」部件（人 入 分 六 八）复用同一角度与端点关系；
  - 横折钩类（分 力 九 子 手 化 氏 民）的钩一律左上方向、同一粗细档；
  - 「丶」在 市 六 主 立 今 里一律写成短竖（重心稳定，读作点）。
* **禁止事项**：没有逐字机械挤压或倾斜（docs/02 偏差 D）——所有变形只出现在
  笔画自身的起收笔上；字体本体与海报特效分离（霓虹/描边/旧化一律不写进轮廓）。

对齐语义
--------
横画 `g.hbar(x1, x2, y, weight)` 的 y 是**中心线**，墨迹占 y ± weight/2；
所以「墨迹上缘对齐 820」的横画，中心线必须内缩半个笔画宽。
竖画 `g.vbar(x, y1, y2, weight)` 的 y1/y2 **就是墨迹端点**，不需要内缩。
斜画 `g.diag(x1, y1, x2, y2, weight)` 的两端是中心线端点，收笔为垂直于中心线的平切，
因此实际墨迹会在端点之外多出 (weight/2)·|dy| 的水平余量与 (weight/2)·|dx| 的垂直余量；
本文件所有斜画端点都留出了这段余量，保证墨迹落在 x 60..940 / y 0..820 内。
"""

from __future__ import annotations

import sys
