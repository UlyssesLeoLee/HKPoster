"""HK Poster Heavy —— Jōyō 常用漢字 joyo-w2-s2-001。

本批 32 字，笔画范围 6–9，取自 2010 年文化厅《常用漢字表》。

整体设计取舍
------------
* 字面框：UPM 1000，基线 y=0，上缘 y=820，左右 x 60..940，advance=1000。
  与繁体（zh-HK）汉字完全一致，便于中英日混排时不跳基线。
* 笔画权重：主 96 / 次 92 / 细 84 / 点 84–104，与 zh-HK 繁体同档。
  笔画少的字（会 6 / 行 6 / 全 6 / 社 7 / 京 8）以 96 为主轴，
  不然同批里会「有的太轻、有的太闷」（GLY-001）；
  8–9 画且内部叠横叠竖的字，在拥挤处局部减重到 92 / 84。
* 对齐语义：横画让墨迹上缘/下缘对齐 820 / 0，竖画让墨迹左缘/右缘
  对齐 60 / 940，中心线一律内缩半个笔画宽（_bt / _bb / _v 辅助函数）。
* 内白预算（GLY-006）：密排处横画与横画的墨迹间隙 ≥ 24 单位；
  竖画与竖画的墨迹间隙 ≥ 60 单位；同一部件（如 囗、冂、口、日、目）
  在批内复用同一套坐标骨架，只按位置与大小做光学校正（GLY-004）。
* 同批观感：同一个部件在不同字里复用同一组中心线间距——
  囗（国/回）左右竖在 x=108 / x=892；口（日/目/回）竖心距 ≥ 444；
  冂（同/前）左竖 x=108、右竖 x=892；宀（実/定）宀横 y=760、
  宀点 y=680；子（学）的横折 y=500。这保证并排或成串排版时字面节奏一致。
* 斜画收笔：斜笔的端帽会横向外扩约半个笔画宽，所有斜画的收笔点都收在
  字面框内（后 x≤890、政 x≤890、相 x≥130），避免墨迹越框。
* 交接处理：斜画与竖画相接时，端点一律深入对方笔画内部 ≥ 20 单位，
  避免出现 4 单位级的窄缝并集（窄缝会让轮廓退化成自交/非法轮廓）。

（生成物：font-src/masters/hkposter-joyo-w2-s2-001.ufo 由本 recipe 生成，
改形状请改本文件再重新生成。）
"""

from __future__ import annotations

import sys
from pathlib import Path

FONT_SRC = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(FONT_SRC / "scripts"))

from hkbuild import Glyph, write_ufo  # noqa: E402

W_MAIN = 96
W_SEC = 92
W_THIN = 84
W_DOT = 84

TOP = 820.0
BASE = 0.0
LEFT = 60.0
RIGHT = 940.0
MID = 500.0


# ---------------------------------------------------------------- 笔画辅助


def _h(g: Glyph, x1: float, x2: float, y: float, w: float = W_MAIN) -> None:
    """横画：中心线 y，墨迹占 y±w/2，横向自 x1 到 x2。"""
    g.hbar(x1, x2, y, weight=w)


def _bt(g: Glyph, x1: float, x2: float, top: float = TOP, w: float = W_MAIN) -> None:
    """横画（上缘对齐）：墨迹上缘正好落在 top。"""
    g.hbar(x1, x2, top - w / 2, weight=w)


def _bb(g: Glyph, x1: float, x2: float, base: float = BASE, w: float = W_MAIN) -> None:
    """横画（下缘对齐）：墨迹下缘正好落在 base。"""
    g.hbar(x1, x2, base + w / 2, weight=w)


def _v(g: Glyph, x: float, y_top: float, y_bot: float, w: float = W_MAIN) -> None:
    """竖画：中心线 x，墨迹自 y_top 到 y_bot。"""
    lo, hi = (y_bot, y_top) if y_bot < y_top else (y_top, y_bot)
    g.vbar(x, lo, hi, weight=w)


def _d(g: Glyph, x1: float, y1: float, x2: float, y2: float, w: float = W_MAIN) -> None:
    """斜笔画：中心线自 (x1,y1) 到 (x2,y2)，厚度垂直于中心线。"""
    g.diag(x1, y1, x2, y2, weight=w)


def _dot(g: Glyph, cx: float, cy: float, w: float = W_DOT, h: float = 96) -> None:
    """点／短撇：平行四边形，中心 (cx,cy)。"""
    g.dot(cx, cy, w=w, h=h)


